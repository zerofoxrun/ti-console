const ВИД_ФАЙЛА = 'ti-console-настройки';

/**
 * Что уезжает коллеге: состав и пресет. Счётчики — НЕ уезжают.
 * Чем человек пользуется, видно только ему; в общем файле это лишнее
 * и, в отделе с руководителем, небезвредное.
 */
function вФайл(наст, версияРасширения = '') {
  const функции = {};
  for (const id of НАСТРАИВАЕМЫЕ) функции[id] = !!(наст.функции || {})[id];
  return {
    вид: ВИД_ФАЙЛА,
    версия: ВЕРСИЯ,
    расширение: String(версияРасширения || ''),
    пресет: наст.пресет || СВОЙ,
    функции,
  };
}

/**
 * Разбор принесённого файла. Возвращает {настройки, замечания, ошибка}.
 *
 * Чужой файл — недоверенный вход: он мог быть от новой версии, от старой,
 * из другого продукта или просто не тем файлом. Ошибка — это отказ,
 * замечания — это «взяли, но не всё».
 */
function изФайла(текстИлиОбъект, текущие, сейчас = Date.now()) {
  let o = текстИлиОбъект;
  if (typeof o === 'string') {
    try { o = JSON.parse(o); } catch (e) {
      return { ошибка: T('Это не JSON: ') + (e.message || T('разбор не удался')), замечания: [] };
    }
  }
  if (!o || typeof o !== 'object' || Array.isArray(o)) {
    return { ошибка: T('В файле нет объекта настроек.'), замечания: [] };
  }
  if (o.вид !== ВИД_ФАЙЛА) {
    return { ошибка: T('Это не файл настроек TI Console ')
                   + T`(ожидалось «${ВИД_ФАЙЛА}», в файле «${o.вид || 'ничего'}»).`,
             замечания: [] };
  }
  const основа = текущие && текущие.функции ? текущие : поумолчанию(сейчас);
  const { настройки, замечания } = нормализовать({
    ...o,
    первыйЗапуск: false,
    подсказкаПоказана: true,
    /* Личное остаётся личным: счётчики и согласие на учёт берутся
     * из своих настроек, а не из принесённого файла. */
    учёт: основа.учёт,
    создано: основа.создано,
    счётчики: основа.счётчики,
  }, сейчас);
  return { настройки, замечания };
}

