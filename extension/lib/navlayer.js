/* =============================================================================
 * navlayer.js — слой для ATT&CK Navigator из кейса
 * =============================================================================
 *
 * ЧТО ЭТО
 * -------
 * Navigator — официальный просмотрщик матрицы ATT&CK. Он принимает файл
 * «слоя»: список техник с подписями и цветами, который накладывается
 * на матрицу. До сих пор аналитик собирал такой слой руками, перенося
 * коды из кейса по одному.
 *
 * ФОРМАТ СВЕРЕН СО СПЕЦИФИКАЦИЕЙ v4.5 (mitre-attack/attack-navigator,
 * layers/spec/v4.5/layerformat.md), а не написан по памяти. Обязательны:
 * name, domain, versions{attack, navigator, layer}. У записи техники
 * обязателен только techniqueID.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
 * -----------------------
 * 1. ПОЛЯ score. Navigator красит ячейки градиентом по числу, и соблазн
 *    выставить «вес» большой. Но число, за которым ничего не стоит, —
 *    это «78% вредоносности»: в документе заказчику оно хуже своего
 *    отсутствия, потому что выглядит измерением. Вместо него цвет
 *    по вердикту, который поставил человек, и сам вердикт словами
 *    в comment.
 *
 * 2. ПОЛЯ tactic. Без него подпись применяется ко ВСЕМ ячейкам техники,
 *    и это то, что нужно: техника в трёх тактиках иначе потребовала бы
 *    трёх записей. Если когда-нибудь понадобится — в слое тактика
 *    пишется коротким именем (lateral-movement), а не отображаемым,
 *    и это надо сверить со спецификацией, а не угадывать.
 *
 * 3. ТЕХНИК ICS. В слое domain ровно один, а каталог у нас смешанный:
 *    enterprise, ICS и mobile. ICS отделяется надёжно по префиксу T0,
 *    enterprise от mobile — нет. Поэтому выгружается enterprise-attack,
 *    а исключённые ICS ПЕРЕСЧИТЫВАЮТСЯ И НАЗЫВАЮТСЯ: молчаливое
 *    исключение неотличимо от «их там и не было».
 *
 * РЕЖИМ КЛИЕНТСКИХ ДАННЫХ
 * -----------------------
 * Название кейса содержит имя заказчика — поля «клиент» у кейса нет
 * с 0.29.0, и имя живёт в названии свободным текстом (см. cases.js,
 * normalizeStore). Поэтому в клиентском режиме название обезличивается,
 * а комментарии (вердикт, «чем проверен», заметка) не выгружаются вовсе.
 * ========================================================================== */

'use strict';

(function initNavLayer() {

if (typeof globalThis !== 'undefined' && globalThis.TINavLayer) return;

/* Версия формата слоя и минимальная версия Navigator — из спецификации.
 * Вынесены константами, потому что попадают в файл и проверяются тестом. */
const ВЕРСИЯ_СЛОЯ = '4.5';
const ВЕРСИЯ_NAVIGATOR = '4.9.0';
const ДОМЕН = 'enterprise-attack';

/* Цвет по вердикту аналитика.
 *
 * unknown ЦВЕТА НЕ ПОЛУЧАЕТ. «Не проверено» обязано выглядеть как
 * не проверено, а не как ещё один оттенок: серая ячейка в ряду цветных
 * читается как вывод, которого никто не делал. */
const ЦВЕТ = {
  malicious:  '#d94f4f',
  suspicious: '#d29922',
  clean:      '#3fb950',
  irrelevant: '#6b7787',
};

const СЛОВО = {
  malicious:  T('вредоносный'),
  suspicious: T('подозрительный'),
  clean:      T('чистый'),
  irrelevant: T('не относится'),
  unknown:    T('не проверен'),
};

/** Техника ли это и в каком виде. Возвращает канонический id либо ''. */
function идТехники(значение) {
  const s = String(значение || '').trim().toUpperCase()
    .replace(/\//g, '.').replace(/\.$/, '');
  return /^T\d{4}(\.\d{3})?$/.test(s) ? s : '';
}

/**
 * Собрать слой.
 *
 * @param {object} кейс   { title, tlp }
 * @param {Array}  items  индикаторы кейса (берутся только type === 'attack')
 * @param {object} опции  { версияATTACK, режим: 'public'|'client', дата }
 * @returns {{ слой: object|null, заметки: string[], всего: number }}
 *
 * Пустой результат возвращается как слой: null и причина в заметках —
 * валидный файл с пустым массивом техник хуже отказа: он выглядит
 * как «в кейсе нет техник», даже если техники были, но все оказались ICS.
 */
function собрать(кейс, items, опции = {}) {
  const режим = опции.режим === 'client' ? 'client' : 'public';
  const заметки = [];

  /* Техники берутся ТОЛЬКО из кейса, а не из каталога: слой на 918
   * техник — это картинка «мы видели всё», то есть ничего. */
  const свои = (items || []).filter((i) => i && i.type === 'attack');

  const ics = [];
  const видели = new Map();          // id -> запись; повтор в кейсе не удваивает ячейку
  for (const i of свои) {
    const id = идТехники(i.value);
    if (!id) continue;
    /* Отбор по МАТРИЦЕ, а не по префиксу.
     *
     * Префикс T0 почти работает: 81 техника ICS из 97 именно такая.
     * Но T1691, T1692, T1693 и их подтехники живут в ICS с обычным
     * префиксом T1, и отбор по строке пропускал их в слой enterprise
     * молча. Поймано тестом матрицы на настоящем каталоге.
     *
     * Функция принадлежности передаётся снаружи: модуль чистый
     * и каталога не читает. Без неё остаётся прежний отбор
     * по префиксу — он лучше, чем никакого. */
    const чья = typeof опции.матрицаТехники === 'function'
      ? опции.матрицаТехники(id)
      : (id.startsWith('T0') ? 'ics' : null);
    if (чья && чья !== ДОМЕН.replace('-attack', '')) { ics.push(id); continue; }
    if (!чья && id.startsWith('T0')) { ics.push(id); continue; }
    if (видели.has(id)) continue;

    const запись = { techniqueID: id };
    const цвет = ЦВЕТ[i.verdict];
    if (цвет) запись.color = цвет;

    if (режим !== 'client') {
      const части = [
        СЛОВО[i.verdict] || null,
        i.verdictSource ? String(i.verdictSource).trim() : null,
        i.note ? String(i.note).trim() : null,
      ].filter(Boolean);
      if (части.length) запись.comment = части.join(' · ');
    }
    видели.set(id, запись);
  }

  if (ics.length) {
    const уник = [...new Set(ics)];
    заметки.push(T`не вошли ${уник.length} техник из других матриц `
      + `(${уник.slice(0, 3).join(', ')}${уник.length > 3 ? '…' : ''}): `
      + T`у слоя один домен, выгружается ${ДОМЕН}`);
  }

  if (!видели.size) {
    заметки.unshift(ics.length
      ? T('в кейсе есть только техники других матриц — слой enterprise собирать не из чего')
      : T('в кейсе нет техник ATT&CK'));
    return { слой: null, заметки, всего: 0 };
  }

  /* Версия ATT&CK берётся из каталога, а не пишется константой:
   * каталог обновляется, и слой, утверждающий прошлый выпуск, — это
   * тихое враньё в файле, который уедет заказчику. */
  const версияATTACK = String(опции['версияATTACK'] || '').trim();
  if (!версияATTACK) {
    заметки.push(T('выпуск ATT&CK неизвестен — поле versions.attack пустое'));
  }

  const дата = опции.дата || new Date().toISOString().slice(0, 10);
  const имя = режим === 'client'
    ? T`Кейс от ${дата}`
    : (String(кейс && кейс.title || '').trim() || T`Кейс от ${дата}`);

  if (режим === 'client') {
    заметки.push(T('режим клиентских данных: название обезличено, комментарии не выгружены'));
  }

  const слой = {
    name: имя,
    domain: ДОМЕН,
    description: T('Черновик из TI Console. Техники отмечены аналитиком ')
      + T('при разборе, а не выведены автоматически.'),
    versions: {
      attack: версияATTACK,
      navigator: ВЕРСИЯ_NAVIGATOR,
      layer: ВЕРСИЯ_СЛОЯ,
    },
    techniques: [...видели.values()],
  };
  return { слой, заметки, всего: видели.size };
}

/** Готовый текст файла. null, если собирать нечего. */
function файл(кейс, items, опции) {
  const r = собрать(кейс, items, опции);
  return r.слой ? JSON.stringify(r.слой, null, 2) : null;
}

const NAV_API = { собрать, файл, идТехники, ЦВЕТ, СЛОВО, ВЕРСИЯ_СЛОЯ, ВЕРСИЯ_NAVIGATOR, ДОМЕН };
if (typeof module !== 'undefined' && module.exports) module.exports = NAV_API;
if (typeof globalThis !== 'undefined') globalThis.TINavLayer = NAV_API;

})();
