/* =============================================================================
 * localfacts.js — что можно сказать о значении, НЕ выходя в сеть
 * =============================================================================
 *
 * ЗАЧЕМ
 * -----
 * Аналитик смотрит на список из тридцати значений и решает, с какого
 * начинать. Половину этого решения можно принять, ничего не спрашивая
 * у интернета: 10.0.0.1 — адрес клиента, а не атакующего; `xn--80ak6aa92e`
 * читается как `аррӏе`; T1059.001 — это PowerShell; хеш длиной 40 —
 * SHA-1, а не SHA-256, и искать его надо иначе.
 *
 * Сейчас всё это аналитик держит в голове либо идёт смотреть в браузер.
 *
 * ГРАНИЦА, КОТОРУЮ ЭТОТ МОДУЛЬ НЕ ПЕРЕХОДИТ
 * ------------------------------------------
 * Здесь НЕТ ни одного сетевого вызова и не будет. Всё, что тут есть,
 * выводится из самого значения и из того, что уже лежит в пакете
 * (каталог ATT&CK, список TLD). Как только факт требует запроса —
 * он не факт, а обогащение, и ему здесь не место: обогащение означает,
 * что имя расследуемого хоста ушло наружу.
 *
 * И ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО
 * --------------------------
 * Оценок. Ни «похоже на фишинг», ни «уровень риска 78». Число, за которым
 * ничего не стоит, в отчёте клиенту хуже его отсутствия: оно выглядит
 * измерением. Здесь только то, что проверяемо: класс адреса по RFC,
 * зона домена, алгоритм по длине хеша, название техники по каталогу.
 * ========================================================================== */

'use strict';

(function initLocalFacts() {

if (typeof globalThis !== 'undefined' && globalThis.TIFacts) return;

/* Пояснения к классам адресов. Словами, а не кодом: «cgnat» аналитику
 * ничего не говорит, а «адрес провайдера, не абонента» говорит. */
const КЛАСС_IPV4 = {
  private: [T('частный диапазон (RFC 1918)'), T('в интернете не маршрутизируется: принадлежит той сети, где встречен')],
  loopback: [T('петля (127.0.0.0/8)'), T('адрес самой машины, наружу не маршрутизируется')],
  'link-local': ['link-local (169.254.0.0/16)', T('выдаётся, когда DHCP не ответил')],
  reserved: [T('зарезервирован (0.0.0.0/8)'), T('в сети такого источника быть не может')],
  cgnat: ['CGNAT (100.64.0.0/10)', T('адрес провайдера, а не абонента — по нему абонент не определяется')],
  'multicast-reserved': [T('multicast или зарезервирован (224.0.0.0/4 и выше)'), ''],
  global: [T('маршрутизируемый'), T('обычный публичный адрес')],
};

/* Диапазоны для документации: RFC 5737 и RFC 3849. Встретив такой адрес
 * в «боевом» отчёте, стоит насторожиться — это пример, а не индикатор. */
const ПРИМЕРНЫЕ_IPV4 = [
  [[192, 0, 2], 'RFC 5737, TEST-NET-1'],
  [[198, 51, 100], 'RFC 5737, TEST-NET-2'],
  [[203, 0, 113], 'RFC 5737, TEST-NET-3'],
];

const ДЛИНА_ХЕША = { 32: 'MD5', 40: 'SHA-1', 64: 'SHA-256', 128: 'SHA-512' };

function факт(имя, значение, пояснение = '') {
  return { имя, значение, пояснение };
}

/* Склонение после числа. Мелочь, но «32 символов» и «5 метки» в тексте,
 * который аналитик копирует в отчёт, читаются как небрежность —
 * а отчёт уходит клиенту. */
function склонение(n, одна, две, много) {
  const с = Math.abs(n) % 100, е = с % 10;
  if (с > 10 && с < 20) return много;
  if (е > 1 && е < 5) return две;
  if (е === 1) return одна;
  return много;
}
const счётом = (n, а, б, в) => `${n.toLocaleString('ru')} ${склонение(n, а, б, в)}`;

/* --------------------------------------------------------------- IPv4 --- */
function ipv4(v) {
  const out = [];
  const cls = (globalThis.IOC && IOC.ipv4Class) ? IOC.ipv4Class(v) : null;
  if (cls && КЛАСС_IPV4[cls]) {
    const [текст, пояснение] = КЛАСС_IPV4[cls];
    out.push(факт(T('диапазон'), текст, пояснение));
  }
  const части = v.split('.').map(Number);
  for (const [префикс, откуда] of ПРИМЕРНЫЕ_IPV4) {
    if (префикс.every((n, i) => части[i] === n)) {
      out.push(факт('внимание', T('адрес из диапазона для примеров'),
                    откуда + T(' — в отчёте это чаще пример, чем индикатор')));
    }
  }
  /* Первый октет 1–223 и последний 0 либо 255 — почти наверняка
   * адрес сети или широковещательный, а не узел. Почти — потому что
   * зависит от маски, которой у нас нет; поэтому формулировка осторожная. */
  if (части[3] === 0) out.push(факт(T('форма'), T('оканчивается на .0'), T('часто адрес сети, а не узла')));
  if (части[3] === 255) out.push(факт(T('форма'), T('оканчивается на .255'), T('часто широковещательный адрес')));
  return out;
}

/* --------------------------------------------------------------- IPv6 --- */
function ipv6(v) {
  const н = v.toLowerCase();
  const out = [];
  if (н === '::1') out.push(факт(T('диапазон'), T('петля (::1)'), T('адрес самой машины')));
  else if (н.startsWith('fe80:')) out.push(факт(T('диапазон'), 'link-local (fe80::/10)', T('не маршрутизируется за пределы сегмента')));
  else if (/^f[cd]/.test(н)) out.push(факт(T('диапазон'), 'unique local (fc00::/7)', T('аналог частного диапазона IPv4')));
  else if (н.startsWith('2001:db8')) out.push(факт('внимание', T('диапазон для примеров'), T('RFC 3849 — в отчёте это пример')));
  else if (н.startsWith('ff')) out.push(факт(T('диапазон'), 'multicast (ff00::/8)', ''));
  else out.push(факт(T('диапазон'), T('глобальный'), T('обычный публичный адрес')));
  if (н.includes('::')) out.push(факт(T('форма'), T('сокращённая запись'), T('поиск по логам может не найти её как есть')));
  return out;
}

/* -------------------------------------------------------------- подсеть - */
function cidr(v) {
  const [адрес, маска] = v.split('/');
  const бит = Number(маска);
  const адресов = Math.pow(2, 32 - бит);
  const узлов = бит >= 31 ? адресов : адресов - 2;   // сеть и broadcast
  return [
    факт(T('размер'), счётом(адресов, T('адрес'), T('адреса'), T('адресов')),
         бит >= 31 ? '' : T('из них узлов ') + узлов.toLocaleString('ru')),
    ...ipv4(адрес).slice(0, 1),
  ];
}

/* --------------------------------------------------------------- домен -- */
function домен(v) {
  const out = [];
  const метки = v.replace(/\.$/, '').split('.');
  const tld = метки[метки.length - 1].toLowerCase();
  out.push(факт(T('зона'), '.' + tld, ''));
  out.push(факт(T('уровень'), счётом(метки.length, T('метка'), T('метки'), T('меток')),
                метки.length > 3 ? T('много поддоменов — типично для конструкторов и динамического DNS') : ''));

  /* Punycode читается глазами неверно, и именно на этом строится
   * подмена бренда. Показать вторую форму — единственный способ
   * увидеть, что перед тобой. */
  const пуни = метки.filter((m) => /^xn--/i.test(m));
  if (пуни.length) {
    /* Читаемую форму здесь НЕ показываем, и это не лень.
     * URL.hostname в браузере отдаёт обратно тот же punycode, а свой
     * декодер IDN — это таблица Unicode в пакете ради одной строки.
     * Сказать «имя записано кодировкой IDN, глазами оно выглядит иначе»
     * — честно и достаточно: дальше человек откроет его в инструменте.
     * Показать ЧАСТИЧНО раскодированное имя было бы хуже молчания. */
    out.push(факт('punycode', пуни.join(', '),
                  T('записан кодировкой IDN — на вид может совпадать с латинским именем')));
  } else if (/[^\x00-\x7F]/.test(v)) {
    out.push(факт(T('не латиница'), T('в имени есть нелатинские символы'),
                  T('у такого имени есть вторая форма (xn--…), и в логах будет она')));
  }
  return out;
}

/* ----------------------------------------------------------------- URL -- */
function url(v) {
  const out = [];
  let u;
  try { u = new URL(v); } catch (_) { return [факт(T('форма'), T('не разбирается как URL'), '')]; }
  out.push(факт(T('хост'), u.hostname, ''));
  if (u.port) out.push(факт(T('порт'), u.port, T('нестандартный порт указан явно')));
  if (u.protocol === 'http:') out.push(факт(T('схема'), 'http', T('без шифрования')));
  if (u.username || u.password) {
    out.push(факт('внимание', T('в адресе есть логин или пароль'),
                  T('форма user@host используется для маскировки настоящего хоста')));
  }
  if (u.pathname && u.pathname !== '/') {
    const файл = u.pathname.split('/').pop();
    if (файл && файл.includes('.')) {
      out.push(факт(T('файл в пути'), файл, ''));
    }
  }
  if (u.search) {
    const n = [...u.searchParams.keys()].length;
    out.push(факт(T('параметры'), счётом(n, T('параметр'), T('параметра'), T('параметров')), ''));
  }
  /* Адрес вместо имени — не улика, но повод посмотреть: у обычного
   * сервиса есть доменное имя. */
  if (/^\d{1,3}(\.\d{1,3}){3}$/.test(u.hostname)) {
    out.push(факт(T('форма'), T('хост задан адресом, а не именем'), ''));
  }
  return out;
}

/* ---------------------------------------------------------------- хеш --- */
function хеш(v) {
  const alg = ДЛИНА_ХЕША[v.length];
  const out = [факт(T('длина'), счётом(v.length, T('символ'), T('символа'), T('символов')),
                    alg ? T`это ${alg}` : '')];
  /* Хеш пустого файла попадает в отчёты регулярно и не значит ничего.
   * Знать это наизусть невозможно, а увидеть — полезно. */
  const ПУСТЫЕ = {
    d41d8cd98f00b204e9800998ecf8427e: T('MD5 пустого файла'),
    da39a3ee5e6b4b0d3255bfef95601890afd80709: T('SHA-1 пустого файла'),
    e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855: T('SHA-256 пустого файла'),
  };
  const пусто = ПУСТЫЕ[v.toLowerCase()];
  if (пусто) out.push(факт('внимание', пусто, T('в качестве индикатора бесполезен')));
  return out;
}

/* -------------------------------------------------------------- ATT&CK -- */
function attack(v) {
  const A = globalThis.TIAttack;
  if (!A) return [];
  const t = A.техника(v);
  if (!t) {
    /* Различаем «каталога нет» и «техники нет». Второе — находка:
     * в отчёте стоит идентификатор, которого в ATT&CK не существует. */
    if (!A.загружен()) return [факт(T('каталог'), T('не загружен'), T('расшифровать нечем'))];
    return [факт('внимание', T('такой техники в ATT&CK нет'),
                 T('в каталоге его нет: либо опечатка, либо идентификатор выдуман'))];
  }
  const out = [факт(T('техника'), t.название, '')];
  if (t.тактики.length) out.push(факт(T('тактики'), t.тактики.join(', '), ''));
  const род = A.родитель(t.id);
  if (род) {
    const р = A.техника(род);
    if (р) out.push(факт(T('родительская'), `${род} — ${р.название}`, ''));
  }
  return out;
}

/* ----------------------------------------------------------------- CVE -- */
function cve(v) {
  const m = /^CVE-(\d{4})-/i.exec(v);
  if (!m) return [];
  const год = Number(m[1]);
  const сейчас = new Date().getFullYear();
  const out = [факт(T('год'), m[1], '')];
  /* Год в идентификаторе — это год РЕЗЕРВИРОВАНИЯ, а не публикации,
   * и путать их — обычная ошибка. Поэтому пояснение, а не вывод. */
  if (год < сейчас - 1) {
    out.push(факт(T('возраст'), счётом(сейчас - год, T('год'), T('года'), T('лет')) + T(' от резервирования'),
                  T('год в идентификаторе — год резервирования, а не публикации')));
  }
  return out;
}

/* ------------------------------------------------- прочие короткие ------ */
function почта(v) {
  const домен_ = v.split('@').pop();
  return [факт(T('домен'), домен_, ''), ...домен(домен_).slice(0, 1)];
}

function мессенджер(v, тип) {
  const платформа = тип === 'tgchan' ? 'Telegram' : 'Discord';
  const приглашение = /joinchat|\/\+|\/invite\/|discord\.gg/i.test(v);
  return [
    факт(T('платформа'), платформа, ''),
    факт(T('вид'), приглашение ? T('приглашение в закрытую группу') : T('публичный канал'),
         приглашение ? T('одноразовые ссылки часто перестают работать к моменту разбора') : ''),
  ];
}

function кошелёк(v, тип) {
  if (тип === 'eth') return [факт(T('формат'), T('адрес Ethereum, 20 байт'), '')];
  if (/^bc1/i.test(v)) return [факт(T('формат'), 'Bech32 (SegWit)', '')];
  if (/^3/.test(v)) return [факт(T('формат'), 'P2SH', '')];
  return [факт(T('формат'), T('P2PKH (устаревший)'), '')];
}

function путьWindows(v) {
  const файл = v.split('\\').pop();
  const out = [факт(T('файл'), файл, '')];
  const системный = /^[A-Za-z]:\\Windows\\/i.test(v);
  if (системный) {
    out.push(факт(T('расположение'), T('системный каталог Windows'),
                  T('штатный файл в штатном месте — но именно такие и используют')));
  } else if (/\\(Temp|AppData|ProgramData|Users\\Public)\\/i.test(v)) {
    out.push(факт(T('расположение'), T('временный или пользовательский каталог'),
                  T('исполняемый файл здесь — повод посмотреть')));
  }
  return out;
}

/* ----------------------------------------------------------- диспетчер -- */
const ПО_ТИПУ = {
  ipv4, ipv6, cidr, url, cve, attack,
  domain: домен, onion: домен, email: почта,
  md5: хеш, sha1: хеш, sha256: хеш, sha512: хеш,
  winpath: путьWindows,
  tgchan: (v) => мессенджер(v, 'tgchan'),
  dsinvite: (v) => мессенджер(v, 'dsinvite'),
  btc: (v) => кошелёк(v, 'btc'),
  eth: (v) => кошелёк(v, 'eth'),
};

/**
 * Факты о значении. Всегда массив, возможно пустой.
 * Пустой массив — нормальный ответ: у ASN и ключа реестра сказать
 * без сети нечего, и придумывать ради заполненности нельзя.
 */
function факты(тип, значение) {
  const f = ПО_ТИПУ[тип];
  if (!f) return [];
  try {
    return f(String(значение)) || [];
  } catch (_) {
    // Сломаться на одном значении и утащить за собой весь список нельзя.
    return [];
  }
}

const FACTS_API = { факты, факт };
if (typeof module !== 'undefined' && module.exports) module.exports = FACTS_API;
if (typeof globalThis !== 'undefined') globalThis.TIFacts = FACTS_API;

})();
