/* =============================================================================
 * compat.js — слой совместимости с Chrome
 * =============================================================================
 *
 * ЗАЧЕМ
 * -----
 * Весь код расширения написан на `browser.*` с промисами — так устроен
 * WebExtensions API в Firefox. В Chrome до 148-й версии пространства имён
 * `browser` нет вовсе, есть только `chrome`
 * (https://developer.mozilla.org/docs/Mozilla/Add-ons/WebExtensions/Chrome_incompatibilities).
 *
 * Этот файл подключается ПЕРВЫМ везде: в фоне, в новой вкладке, в панели,
 * во всплывающем окне. В Firefox он не делает ничего.
 *
 * ПОЧЕМУ НЕ ПОЛИФИЛЛ MOZILLA
 * --------------------------
 * webextension-polyfill решает задачу «колбэки -> промисы», которой у нас
 * нет: в Chrome MV3 API уже промисные. Тащить внешнюю зависимость в XPI,
 * который подписывается и проверяется рецензентом, ради псевдонима
 * не стоит: каждая внешняя библиотека — это то, что придётся объяснять.
 *
 * ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ
 * ------------------------
 * Он НЕ подменяет отсутствующие в Chrome API. `browser.dns`,
 * `browser.browserSettings`, `browser.sidebarAction` в Chrome не появятся
 * от переименования. Подменять их заглушками нельзя: заглушка, молча
 * возвращающая пустоту, — это ровно тот способ соврать аналитику, против
 * которого построен весь разбор. Вместо этого здесь есть `TICompat.нет()`,
 * которым код спрашивает, доступна ли возможность, и говорит об этом вслух.
 * ========================================================================== */

'use strict';

(function initCompat() {
  if (typeof globalThis === 'undefined') return;

  /* Псевдоним. Именно псевдоним, а не копия: методы обязаны вызываться
   * на исходном объекте, иначе часть реализаций Chrome теряет `this`. */
  if (typeof globalThis.browser === 'undefined' && typeof globalThis.chrome !== 'undefined') {
    globalThis.browser = globalThis.chrome;
  }

  const b = globalThis.browser;

  /* Какой это браузер — определяется по НАЛИЧИЮ возможностей, а не
   * по строке user agent: строку подделывают, а API либо есть, либо нет. */
  const firefox = !!(b && b.runtime && typeof b.runtime.getBrowserInfo === 'function');

  /* Возможности, которых в одном из браузеров нет. Список закрытый:
   * каждая строка — место, где интерфейс обязан сказать правду о том,
   * что функция недоступна. */
  const ВОЗМОЖНОСТИ = {
    // Резолв имени средствами браузера, без единого сетевого запроса от нас.
    // В Chrome API dns нет. Единственный способ получить адрес там —
    // сходить во внешний сервис, то есть отправить туда имя хоста
    // расследуемой страницы. Это запрещено требованием проекта, поэтому
    // в Chrome функции не будет — и об этом надо написать, а не промолчать.
    dns: !!(b && b.dns && typeof b.dns.resolve === 'function'),

    // Тёмная схема для содержимого страниц. Косметика.
    contentColorScheme: !!(b && b.browserSettings
      && b.browserSettings.overrideContentColorScheme),

    // Боковая панель: в Firefox sidebarAction, в Chrome sidePanel.
    sidebar: !!(b && b.sidebarAction),
    sidePanel: !!(b && b.sidePanel),
  };

  const API = {
    firefox,
    chrome: !firefox,
    есть: (имя) => ВОЗМОЖНОСТИ[имя] === true,
    нет: (имя) => ВОЗМОЖНОСТИ[имя] !== true,
    возможности: () => ({ ...ВОЗМОЖНОСТИ }),

    /* Открыть боковую панель. Единственное место, где два браузера
     * расходятся по действию, а не по наличию.
     *
     * ВАЖНО: и sidebarAction.open, и sidePanel.open работают только
     * внутри пользовательского жеста — первый же await его теряет.
     * Поэтому функция НЕ async и возвращает то, что вернул браузер. */
    открытьПанель(tabId) {
      if (ВОЗМОЖНОСТИ.sidebar) return b.sidebarAction.open();
      if (ВОЗМОЖНОСТИ.sidePanel) return b.sidePanel.open({ tabId });
      return Promise.reject(new Error('боковой панели нет в этом браузере'));
    },
  };

  globalThis.TICompat = API;
})();
