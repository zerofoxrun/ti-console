/* Проверки myplaybooks.js.
 *
 * Модуль чистый, поэтому проверяется без браузера. Цена ошибки здесь —
 * набор, который выглядит настроенным, а открывает не то: либо молча
 * короче, либо не по тому типу. Оба случая неотличимы от исправной
 * работы, пока не сверишь руками.
 */
'use strict';

globalThis.T = (s, ...a) => (Array.isArray(s)
  ? s.raw.reduce((acc, ч, i) => acc + ч + (i < a.length ? a[i] : ''), '')
  : s);

const M = require('./myplaybooks.js');
const PB = require('./playbook.js');

let всего = 0;
let плохо = 0;
function check(имя, условие, деталь = '') {
  всего++;
  if (!условие) { плохо++; console.log(`ПЛОХО  ${имя}${деталь ? ' — ' + деталь : ''}`); }
}

/* Маленький реестр: сетевые, доменный, файловый и внутренний сервисы. */
const TOOLS = [
  { id: 'vt-ip', name: 'VirusTotal IP', types: ['ipv4'], exposure: 'public' },
  { id: 'shodan', name: 'Shodan', types: ['ipv4', 'ipv6'], exposure: 'public' },
  { id: 'ipam', name: 'Внутренний IPAM', types: ['ipv4'], exposure: 'limited' },
  { id: 'crtsh', name: 'crt.sh', types: ['domain'], exposure: 'public' },
  { id: 'bazaar', name: 'MalwareBazaar', types: ['sha256', 'md5'], exposure: 'public' },
];
const ВСТРОЕННЫЕ = [
  { id: 'c2-ip', name: 'Адрес', types: ['ipv4'], steps: ['vt-ip', 'shodan'] },
  { id: 'phish', name: 'Домен', types: ['domain'], steps: ['crtsh', 'vt-ip'] },
];

/* ------------------------------------------------- пустое хранилище ----- */
{
  const { хранилище, замечания } = M.нормализовать(null);
  check('пусто из null', хранилище.набор.steps.length === 0);
  check('пусто без замечаний', замечания.length === 0);
  check('ненастроенный набор не отдаётся', M.набор(хранилище, TOOLS) === null);
  check('и списком тоже пуст', M.список(хранилище, TOOLS).length === 0);
  check('настроен говорит нет', M.настроен(хранилище) === false);
  check('не объект даёт пустое с замечанием',
        M.нормализовать('строка').замечания.length === 1);
  check('массив вместо объекта тоже', M.нормализовать([]).хранилище.набор.steps.length === 0);
}

/* ---------------------------------- один список, разные типы на выходе -- */
{
  const х = M.сохранить(M.пусто(),
    { name: 'Мои проверки', steps: ['vt-ip', 'ipam', 'crtsh', 'bazaar'] });
  check('настроен говорит да', M.настроен(х) === true);

  const н = M.набор(х, TOOLS);
  check('набор отдаётся', н !== null);
  check('типы выведены из состава',
        н.types.slice().sort().join(',') === 'domain,ipv4,md5,sha256',
        JSON.stringify(н.types));
  check('идентификатор зарезервированный', н.id === 'мои-проверки');
  check('набор помечен своим', н.свой === true);

  /* ГЛАВНОЕ СВОЙСТВО: список один, а открывается из него то,
   * что подходит найденному типу. */
  const поIP = PB.planPlaybook(н, TOOLS, 'ipv4', 'public', false);
  check('для IPv4 идут только сетевые шаги',
        поIP.steps.map((t) => t.id).join(',') === 'vt-ip,ipam',
        JSON.stringify(поIP.steps.map((t) => t.id)));
  const поДомену = PB.planPlaybook(н, TOOLS, 'domain', 'public', false);
  check('для домена — только доменный',
        поДомену.steps.map((t) => t.id).join(',') === 'crtsh',
        JSON.stringify(поДомену.steps.map((t) => t.id)));
  const поХешу = PB.planPlaybook(н, TOOLS, 'sha256', 'public', false);
  check('для хеша — только файловый',
        поХешу.steps.map((t) => t.id).join(',') === 'bazaar',
        JSON.stringify(поХешу.steps.map((t) => t.id)));
  check('отброшенные по типу названы именно причиной TYPE',
        поХешу.skipped.every((s) => s.why === PB.PB_SKIP.TYPE),
        JSON.stringify(поХешу.skipped));

  /* Порядок сервисов в наборе — это порядок открытия вкладок. */
  const обратный = M.сохранить(M.пусто(), { name: 'A', steps: ['ipam', 'vt-ip'] });
  const план = PB.planPlaybook(M.набор(обратный, TOOLS), TOOLS, 'ipv4', 'public', false);
  check('порядок шагов сохраняется', план.steps.map((t) => t.id).join(',') === 'ipam,vt-ip',
        JSON.stringify(план.steps.map((t) => t.id)));
}

/* --------------------------------------------- гейты действуют и здесь -- */
{
  const х = M.сохранить(M.пусто(), { name: 'A', steps: ['vt-ip', 'ipam'] });
  const н = M.набор(х, TOOLS);

  const клиент = PB.planPlaybook(н, TOOLS, 'ipv4', 'client', false);
  check('в клиентском режиме публичный шаг отброшен',
        клиент.steps.length === 1 && клиент.steps[0].id === 'ipam',
        JSON.stringify(клиент.steps.map((t) => t.id)));
  check('и причина названа режимом данных',
        клиент.skipped[0].why === PB.PB_SKIP.TLP, JSON.stringify(клиент.skipped));

  const свой = PB.planPlaybook(н, TOOLS, 'ipv4', 'public', true);
  check('для своего адреса публичный шаг тоже отброшен',
        свой.steps.length === 1 && свой.skipped[0].why === PB.PB_SKIP.OWN,
        JSON.stringify(свой.skipped));
}

/* --------------- неизвестный сервис НЕ вычищается молча ----------------- */
{
  const х = M.сохранить(M.пусто(), { name: 'A', steps: ['vt-ip', 'нетТакого'] });
  check('шаг с несуществующим сервисом сохранён, а не выкинут',
        х.набор.steps.length === 2, JSON.stringify(х.набор.steps));
  const пр = M.проверить(х.набор, TOOLS);
  check('и назван ошибкой при проверке',
        пр.ошибки.some((о) => /нетТакого/.test(о)), JSON.stringify(пр.ошибки));
  check('в типы он при этом не добавляет ничего',
        M.набор(х, TOOLS).types.join(',') === 'ipv4');
  const план = PB.planPlaybook(M.набор(х, TOOLS), TOOLS, 'ipv4', 'public', false);
  check('и при открытии назван как отсутствующий в реестре',
        план.skipped.some((s) => s.why === PB.PB_SKIP.MISSING),
        JSON.stringify(план.skipped));
}

/* ------------------------------------------------- без реестра ---------- */
{
  const х = M.сохранить(M.пусто(), { name: 'A', steps: ['vt-ip'] });
  check('без реестра набор не подставляется наугад', M.набор(х, []) === null);
  check('и со сплошь неизвестными сервисами тоже',
        M.набор(M.сохранить(M.пусто(), { name: 'A', steps: ['ууу'] }), TOOLS) === null);
}

/* ---------------------------------------------------------- проверка ---- */
{
  const пусто = M.проверить({ name: '', steps: [] }, TOOLS);
  check('пустой набор даёт две ошибки', пусто.ошибки.length === 2,
        JSON.stringify(пусто.ошибки));
  check('типов у набора не требуют',
        !пусто.ошибки.some((о) => /тип/.test(о)), JSON.stringify(пусто.ошибки));

  const дубль = M.проверить({ name: 'A', steps: ['vt-ip', 'vt-ip'] }, TOOLS);
  /* Повтор отсекается ещё при записи, но проверка обязана ловить его
   * и в том, что пришло из файла настроек мимо интерфейса. */
  check('повтор сервиса — ошибка', дубль.ошибки.some((о) => /дважды/.test(о)),
        JSON.stringify(дубль.ошибки));
  check('а при сохранении повтор не записывается',
        M.сохранить(M.пусто(), { name: 'A', steps: ['vt-ip', 'vt-ip'] })
          .набор.steps.length === 1);

  const всеПубличные = M.проверить({ name: 'A', steps: ['vt-ip', 'crtsh'] }, TOOLS);
  check('набор из одних публичных предупреждает про клиентский режим',
        всеПубличные.предупреждения.some((п) => /клиентск/.test(п)),
        JSON.stringify(всеПубличные.предупреждения));
  check('и это предупреждение, а не ошибка', всеПубличные.ошибки.length === 0);

  const сОграниченным = M.проверить({ name: 'A', steps: ['vt-ip', 'ipam'] }, TOOLS);
  check('с ограниченным сервисом предупреждения нет',
        сОграниченным.предупреждения.length === 0 && сОграниченным.ошибки.length === 0,
        JSON.stringify(сОграниченным));

  /* Длина считается по самому населённому типу, а не по длине списка. */
  const много = [];
  const реестр = [];
  for (let i = 0; i < 20; i++) {
    реестр.push({ id: 'ip' + i, name: 'IP' + i, types: ['ipv4'], exposure: 'limited' });
    много.push('ip' + i);
  }
  for (let i = 0; i < 20; i++) {
    реестр.push({ id: 'd' + i, name: 'D' + i, types: ['domain'], exposure: 'limited' });
    много.push('d' + i);
  }
  const длинный = M.проверить({ name: 'A', steps: много }, реестр);
  check('длинный разбор предупреждает числом вкладок',
        длинный.предупреждения.some((п) => /20 вкладок/.test(п)),
        JSON.stringify(длинный.предупреждения));
  const короткий = M.проверить(
    { name: 'A', steps: много.slice(0, 10) }, реестр);
  check('сорок сервисов не повод предупреждать, если по типу их десять',
        короткий.предупреждения.length === 0, JSON.stringify(короткий.предупреждения));
}

/* --------------------------------------------------- заготовка ---------- */
{
  const заготовка = M.поВстроенным(ВСТРОЕННЫЕ);
  check('заготовка объединяет шаги без повторов',
        заготовка.join(',') === 'vt-ip,shodan,crtsh', JSON.stringify(заготовка));
  check('заготовка не применяется сама собой',
        M.набор(M.пусто(), TOOLS) === null);
  check('пустые встроенные не роняют', M.поВстроенным(null).length === 0);
}

/* ----------------------------------------------- неизменяемость --------- */
{
  const х = M.сохранить(M.пусто(), { name: 'A', steps: ['vt-ip'] });
  const копия = JSON.stringify(х);
  M.сохранить(х, { name: 'Б', steps: ['crtsh'] });
  check('исходное хранилище не изменилось', JSON.stringify(х) === копия, JSON.stringify(х));
  check('очистка возвращает пустое', M.очистить().набор.steps.length === 0);
}

/* ----------------------------- перенос со старого вида (версия 1) ------- */
{
  /* Так выглядело хранилище, пока наборов было несколько. Переход
   * обязан сохранить то, что человек настраивал, и сказать, что
   * остальное больше не настраивается. */
  const старое = {
    версия: 1,
    свои: [
      { id: 'c2-ip', name: 'Правленый встроенный', types: ['ipv4'], steps: ['vt-ip'] },
      { id: 'мои-проверки', name: 'Мои проверки', types: [], steps: ['ipam', 'crtsh'] },
      { id: 'свой-1', name: 'Ещё один', types: ['ipv4'], steps: ['shodan'] },
    ],
    скрытые: ['phish'],
  };
  const { хранилище, замечания } = M.нормализовать(старое);
  check('перенос взял общий набор, а не первый попавшийся',
        хранилище.набор.steps.join(',') === 'ipam,crtsh',
        JSON.stringify(хранилище.набор));
  check('перенос назвал, сколько записей не перенесено',
        замечания.some((з) => /остальных записей было: 2/.test(з)),
        JSON.stringify(замечания));
  check('версия после переноса новая', хранилище.версия === 2);

  /* Общего набора не было — берётся первый: это и была та настройка,
   * которую человек делал. */
  const безОбщего = M.нормализовать({
    версия: 1,
    свои: [{ id: 'свой-1', name: 'Единственный', types: ['ipv4'], steps: ['shodan'] }],
  });
  check('без общего набора берётся единственный',
        безОбщего.хранилище.набор.steps.join(',') === 'shodan');
  check('и про потери не сообщается, потому что их нет',
        безОбщего.замечания.length === 0, JSON.stringify(безОбщего.замечания));
}

console.log(плохо ? `ПЛОХО: ${плохо} из ${всего}`
                  : `myplaybooks.js: ${всего} проверок, все прошли`);
process.exit(плохо ? 1 : 0);
