/* =============================================================================
 * matrixpng.js — раскладка матрицы ATT&CK в координаты для canvas
 * =============================================================================
 *
 * ЧТО ЭТО
 * -------
 * Чистая геометрия. Здесь нет ни canvas, ни DOM: на вход — модель
 * из matrix.js, на выход — числа (x, y, ширина, высота, готовые строки
 * текста) и палитра. Рисует по этим числам newtab.js.
 *
 * ПОЧЕМУ РАСКЛАДКА ОТДЕЛЬНО ОТ РИСОВАНИЯ
 * --------------------------------------
 * Картинку нельзя проверить тестом: `ctx.fillRect` ничего не возвращает,
 * а сравнивать пиксели — значит переписывать тест при каждом сдвиге
 * на полпикселя. Зато можно проверить ЧИСЛА: что колонок столько же,
 * сколько в модели; что ни одна ячейка не вылезла за холст; что в текст
 * картинки не попало название кейса. Всё, что здесь считается, —
 * проверяемо; всё, что рисуется, — механическое повторение этих чисел.
 *
 * ПОЧЕМУ ТОЛЬКО PNG И НИКОГДА SVG
 * -------------------------------
 * SVG — это текст. Название кейса, заметка аналитика, адрес источника
 * внутри SVG остаются СТРОКАМИ: их видно в «Просмотре кода», их находит
 * grep, их индексирует почтовый шлюз. Вырезанная в клиентском режиме
 * строка, забытая в атрибуте <title>, уедет заказчику как есть и никто
 * этого не заметит. PNG — растр: то, чего нет на картинке, нет нигде.
 *
 * ПОЧЕМУ ПАЛИТРА ФИКСИРОВАНА, А НЕ БЕРЁТСЯ ИЗ ТЕМЫ
 * ------------------------------------------------
 * Картинка уезжает в отчёт и печатается. Тёмная тема на бумаге — это
 * лист, залитый чёрным, и вердикты на нём не читаются. Аналитик с тёмной
 * темой и аналитик со светлой обязаны приложить к отчёту одинаковый файл.
 *
 * КАКИЕ ПОДТЕХНИКИ ПОПАДАЮТ В КАРТИНКУ
 * ------------------------------------
 * Только те, что отмечены в кейсе. Остальные сворачиваются в «+N».
 * Причина арифметическая: в enterprise 618 подтехник на 254 ячейки, и при
 * полном раскрытии холст уходит за 45 млн пикселей — это 180 МБ памяти
 * и отказ toBlob на слабой машине. Причина по существу: покрытие — это
 * «что видели», а не «что бывает»; «видели PowerShell» — факт отчёта,
 * «бывает ещё 13 интерпретаторов» — справочная информация, и её место
 * в ссылке на MITRE, а не в приложении к отчёту.
 * ========================================================================== */

'use strict';

(function initMatrixPng() {

if (typeof globalThis !== 'undefined' && globalThis.TIMatrixPng) return;

/* Палитра. Светлая, печатная, без зависимости от темы интерфейса. */
const ПАЛИТРА = {
  фон:          '#ffffff',
  фонКолонки:   '#f6f7f9',
  текст:        '#14171c',
  текстТусклый: '#5d6675',
  линия:        '#d7dbe3',
  линияСильная: '#bcc3ce',
  вердикт: {
    malicious:  { заливка: '#fdeaea', рамка: '#b91c1c', подпись: T('вредоносная')     },
    suspicious: { заливка: '#fdf1e0', рамка: '#b45309', подпись: T('подозрительная')  },
    clean:      { заливка: '#e7f6ec', рамка: '#15803d', подпись: T('чистая')          },
    irrelevant: { заливка: '#eef0f4', рамка: '#8a93a3', подпись: T('не относится')    },
  },
  /* Не проверено — БЕЗ заливки. Серая ячейка в ряду цветных читается
   * как вывод, которого никто не делал. */
  непроверено:  { заливка: '#ffffff', рамка: '#d7dbe3', подпись: T('не проверялась') },
};

const РАЗМЕТКА = {
  поля: 24,
  колонка: 176,
  зазорКолонок: 8,
  строкаТекста: 14,
  ячейкаОтступ: 5,
  зазорЯчеек: 4,
  подтехника: 16,
  шрифт: 11,
  шрифтШапкиКолонки: 11,
  шрифтЗаголовка: 17,
  шрифтПодзаголовка: 11,
  высотаЗаголовка: 52,
  высотаПодвала: 46,
};

/* Пределы холста.
 *
 * Chrome отказывает примерно на 16384 px по стороне, Firefox — на 32767,
 * но задолго до этого отказывает toBlob: холст 6000×7500 при масштабе 2 —
 * это 180 МБ в памяти. Предел ниже выбран так, чтобы отказ был НАШ
 * и с объяснением, а не браузерный и молчаливый (пустой чёрный PNG
 * без единой ошибки в консоли — именно то, что отдаёт Chrome). */
const ПРЕДЕЛ_СТОРОНЫ = 12000;
const ПРЕДЕЛ_ПЛОЩАДИ = 36e6;

/* Семейство шрифта. Одно и то же при ИЗМЕРЕНИИ и при РИСОВАНИИ —
 * иначе текст мерится одним шрифтом, а рисуется другим, и вылезает
 * за ячейку ровно настолько, насколько они различаются. */
const СЕМЕЙСТВО = 'system-ui, -apple-system, "Segoe UI", Roboto, Arial, sans-serif';

/** Строка шрифта для canvas. Общая точка для мерки и отрисовки. */
function шрифт(размер, жирный = false, семейство = СЕМЕЙСТВО) {
  return `${жирный ? '600 ' : ''}${размер}px ${семейство}`;
}

/** Приблизительная ширина текста, если мерить нечем (Node, тесты). */
function ширинаНаГлаз(текст, размер) {
  return String(текст).length * размер * 0.56;
}

/**
 * Разбить строку на строки, влезающие в ширину.
 * Слово длиннее строки рубится посимвольно: обрезать его многоточием
 * значило бы соврать о названии техники.
 */
function перенести(текст, ширина, размер, измерить, максСтрок = 3) {
  const мерка = измерить || ((т) => ширинаНаГлаз(т, размер));
  const слова = String(текст || '').split(/\s+/).filter(Boolean);
  const строки = [];
  let тек = '';

  const положить = (с) => { if (с) строки.push(с); };

  for (const слово of слова) {
    const проба = тек ? тек + ' ' + слово : слово;
    if (мерка(проба) <= ширина) { тек = проба; continue; }
    положить(тек);
    тек = '';
    if (мерка(слово) <= ширина) { тек = слово; continue; }
    /* Слово само по себе не влезает — рубим. */
    let кусок = '';
    for (const ч of слово) {
      if (мерка(кусок + ч) > ширина && кусок) { положить(кусок); кусок = ч; }
      else кусок += ч;
    }
    тек = кусок;
  }
  положить(тек);

  if (!строки.length) return [''];
  if (строки.length <= максСтрок) return строки;
  /* Переполнение видно по многоточию — и только здесь, где альтернатива
   * (растущая вниз ячейка) ломает раскладку колонки. */
  const урезано = строки.slice(0, максСтрок);
  урезано[максСтрок - 1] = урезано[максСтрок - 1].replace(/.{1,2}$/, '…');
  return урезано;
}

/** Подпись фильтров человеческим языком. Пустые фильтры не называются. */
function описатьФильтры(ф) {
  const части = [];
  const матрицы = { enterprise: 'Enterprise', ics: 'ICS', mobile: 'Mobile' };
  части.push(матрицы[ф.матрица] || ф.матрица || 'Enterprise');
  if (ф.режим === 'кейс') части.push(T('только из кейса'));
  if (ф.режим === 'непокрыто') части.push(T('не покрыто'));
  if (ф.тактика) части.push(T('тактика: ') + ф.тактика);
  if (ф.вердикт) части.push(T('вердикт: ') + ф.вердикт);
  if (ф.платформа) части.push(T('платформа: ') + ф.платформа);
  if (ф.проверено === 'да') части.push(T('только проверенные'));
  if (ф.проверено === 'нет') части.push(T('только не проверенные'));
  return части.join(' · ');
}

/**
 * Разложить модель матрицы в координаты.
 *
 * @param {object} модель   результат TIMatrix.построить
 * @param {object} опции
 *   - название   {string} название кейса (в клиентском режиме НЕ используется)
 *   - дата       {string} YYYY-MM-DD
 *   - выпуск     {string} версия каталога ATT&CK
 *   - фильтры    {object} текущие фильтры — попадают в подзаголовок
 *   - режим      'public' | 'client'
 *   - масштаб    {number} множитель пикселей (по умолчанию 2)
 *   - измерить   {function(текст, шрифтCSS): number} ctx.measureText в браузере
 * @returns {{ширина, высота, масштаб, заголовок, подзаголовок, колонки,
 *            легенда, подвал, палитра, разметка, годится, заметки}}
 */
function разложить(модель, опции = {}) {
  const Р = РАЗМЕТКА;
  const заметки = [];
  const клиентский = опции.режим === 'client';
  const дата = опции.дата || new Date().toISOString().slice(0, 10);
  const масштабЗапрошен = опции.масштаб || 2;

  const семейство = опции.семейство || СЕМЕЙСТВО;
  const мерить = typeof опции.измерить === 'function'
    ? (текст, размер, жирный) => опции.измерить(текст, шрифт(размер, жирный, семейство))
    : (текст, размер) => ширинаНаГлаз(текст, размер);

  /* ЗАГОЛОВОК И TLP-ГЕЙТ.
   *
   * Имя заказчика живёт в названии кейса свободным текстом — поля
   * «клиент» у кейса нет с 0.29.0. Значит в клиентском режиме название
   * не «очищается», а НЕ БЕРЁТСЯ вовсе: очистка требует знать, какая
   * часть строки — имя, а этого никто не знает. */
  const заголовок = клиентский
    ? T`Покрытие ATT&CK — кейс от ${дата}`
    : T`Покрытие ATT&CK — ${String(опции.название || 'без названия').trim()}`;

  const хвост = [];
  хвост.push(дата);
  if (опции.выпуск) хвост.push('ATT&CK ' + опции.выпуск);
  хвост.push(описатьФильтры(опции.фильтры || {}));
  хвост.push(T`${модель.показано} техник из ${модель.всего}`);
  хвост.push(T`в кейсе отмечено: ${модель.вКейсе}`);
  const подзаголовок = хвост.filter(Boolean).join('  ·  ');

  if (клиентский) заметки.push(T('режим клиентских данных: название кейса ')
    + T('и заметки аналитика в картинку не попадают'));

  /* ---- проход 1: высота шапки колонок (одинаковая у всех) ---- */
  const внутри = Р.колонка - Р.ячейкаОтступ * 2;
  let строкШапки = 1;
  const шапки = модель.колонки.map((к) => {
    const строки = перенести(к.тактика, внутри - 22, Р.шрифтШапкиКолонки,
      (т) => мерить(т, Р.шрифтШапкиКолонки, true), 2);
    if (строки.length > строкШапки) строкШапки = строки.length;
    return строки;
  });
  const высотаШапкиКолонки = Р.ячейкаОтступ * 2 + строкШапки * Р.строкаТекста;

  /* ---- проход 2: ячейки ---- */
  const y0 = Р.поля + Р.высотаЗаголовка + высотаШапкиКолонки + Р.зазорЯчеек;
  let самаяВысокая = 0;
  let ячеекВсего = 0, подтехникПоказано = 0, подтехникСвёрнуто = 0;

  const колонки = модель.колонки.map((к, ki) => {
    const x = Р.поля + ki * (Р.колонка + Р.зазорКолонок);
    let y = y0;
    const ячейки = к.ячейки.map((я) => {
      /* В картинку раскрываются ТОЛЬКО подтехники из кейса. Почему —
       * в шапке файла. Свёрнутые не исчезают: их число печатается. */
      const раскрытые = (я.подтехники || []).filter((п) => п.вКейсе);
      const свёрнуто = (я.подтехники || []).length - раскрытые.length;
      подтехникПоказано += раскрытые.length;
      подтехникСвёрнуто += свёрнуто;

      const строки = перенести(я.название, внутри, Р.шрифт,
        (т) => мерить(т, Р.шрифт, false), 3);
      const подстроки = раскрытые.map((п) => ({
        id: п.id,
        вердикт: п.вердикт,
        текст: перенести(п.название, внутри - 8, Р.шрифт - 1,
          (т) => мерить(т, Р.шрифт - 1, false), 1)[0],
      }));

      let h = Р.ячейкаОтступ * 2 + строки.length * Р.строкаТекста;
      if (подстроки.length) h += подстроки.length * Р.подтехника + 2;
      if (свёрнуто) h += Р.подтехника;

      const ячейка = {
        id: я.id, x, y, ширина: Р.колонка, высота: h,
        строки, вердикт: я.вердикт, вКейсе: я.вКейсе,
        приглушена: !!я.приглушена, подтехники: подстроки, свёрнуто,
      };
      y += h + Р.зазорЯчеек;
      ячеекВсего++;
      return ячейка;
    });
    if (y - y0 > самаяВысокая) самаяВысокая = y - y0;
    return { тактика: к.тактика, строкиШапки: шапки[ki], x, y: Р.поля + Р.высотаЗаголовка,
             высотаШапки: высотаШапкиКолонки, счёт: к.ячейки.length, ячейки };
  });

  const ширина = колонки.length
    ? Р.поля * 2 + колонки.length * Р.колонка + (колонки.length - 1) * Р.зазорКолонок
    : 520;
  const высотаСетки = Math.max(самаяВысокая, 40);
  const высота = y0 + высотаСетки + Р.высотаПодвала + Р.поля;

  /* ---- масштаб и пределы холста ---- */
  let масштаб = масштабЗапрошен;
  const превышает = (м) => ширина * м > ПРЕДЕЛ_СТОРОНЫ || высота * м > ПРЕДЕЛ_СТОРОНЫ
    || ширина * м * высота * м > ПРЕДЕЛ_ПЛОЩАДИ;
  while (масштаб > 1 && превышает(масштаб)) масштаб -= 0.5;
  const годится = !превышает(масштаб);
  if (масштаб !== масштабЗапрошен && годится) {
    заметки.push(T`картинка велика: чёткость снижена до ×${масштаб}`);
  }
  if (!годится) {
    заметки.push(T`холст ${Math.round(ширина)}×${Math.round(высота)} не помещается `
      + T('в пределы браузера — сузьте выборку фильтром «тактика» или режимом ')
      + T('«только из кейса»'));
  }

  /* ---- легенда и подвал ---- */
  /* Считаются ТЕХНИКИ, а не ячейки.
   *
   * T1547.001 стоит в двух колонках — Persistence и Privilege Escalation, —
   * потому что так устроена матрица. Считать ячейки значило бы написать
   * в легенде «вредоносных — 4» там, где вредоносных техник три, и это
   * число уехало бы в отчёт заказчику. */
  const учтено = new Set();
  const счётВердиктов = { malicious: 0, suspicious: 0, clean: 0, irrelevant: 0, unknown: 0 };
  const учесть = (id, вердикт) => {
    if (учтено.has(id)) return;
    учтено.add(id);
    const в = вердикт || 'unknown';
    if (в in счётВердиктов) счётВердиктов[в]++;
  };
  for (const к of колонки) {
    for (const я of к.ячейки) {
      учесть(я.id, я.вердикт);
      for (const п of я.подтехники) учесть(п.id, п.вердикт);
    }
  }
  const легенда = Object.keys(ПАЛИТРА.вердикт).map((в) => ({
    вердикт: в, подпись: ПАЛИТРА.вердикт[в].подпись, счёт: счётВердиктов[в],
  }));
  легенда.push({ вердикт: 'unknown', подпись: ПАЛИТРА.непроверено.подпись,
                 счёт: счётВердиктов.unknown });

  const подвал = [];
  подвал.push(T('Цвет ячейки — вердикт аналитика из кейса. Техника без цвета ')
    + T('не проверялась: пустая ячейка не равна «чисто». В легенде считаются ')
    + T('техники, а не ячейки: техника с двумя тактиками стоит в двух колонках.'));
  if (подтехникСвёрнуто) {
    подвал.push(T`Раскрыты только подтехники, отмеченные в кейсе (${подтехникПоказано}); `
      + T`ещё ${подтехникСвёрнуто} свёрнуты и показаны числом «+N».`);
  }
  подвал.push(клиентский
    ? T('Режим клиентских данных: название кейса и заметки аналитика в картинку не вошли.')
    : T('Построено TI Console локально, без обращения к сети.'));

  return {
    ширина, высота, масштаб, годится, семейство,
    заголовок, подзаголовок, колонки, легенда, подвал,
    палитра: ПАЛИТРА, разметка: Р,
    счёт: { ячеек: ячеекВсего, колонок: колонки.length,
            подтехникПоказано, подтехникСвёрнуто, вердикты: счётВердиктов },
    заметки: заметки.concat(модель.заметки || []),
  };
}

/** Имя файла. Название кейса в него не попадает НИКОГДА — включая обычный
 *  режим: имя файла видно в почте, в списке вложений и в логе шлюза. */
function имяФайла(дата) {
  const д = /^\d{4}-\d{2}-\d{2}$/.test(String(дата || ''))
    ? дата : new Date().toISOString().slice(0, 10);
  return `attack-matrix-${д}.png`;
}

/** Весь текст, который попадёт на картинку. Нужен тестам: проверка
 *  «названия кейса на картинке нет» обязана смотреть на ВСЕ строки,
 *  а не на те, про которые вспомнил автор теста. */
function весьТекст(раскладка) {
  const т = [раскладка.заголовок, раскладка.подзаголовок];
  for (const л of раскладка.легенда) т.push(л.подпись, String(л.счёт));
  for (const п of раскладка.подвал) т.push(п);
  for (const к of раскладка.колонки) {
    т.push(к.тактика, ...к.строкиШапки, String(к.счёт));
    for (const я of к.ячейки) {
      т.push(я.id, ...я.строки);
      if (я.свёрнуто) т.push(`+${я.свёрнуто}`);
      for (const п of я.подтехники) т.push(п.id, п.текст);
    }
  }
  return т.join('\n');
}

const API = {
  разложить, имяФайла, весьТекст, перенести, описатьФильтры, шрифт,
  ПАЛИТРА, РАЗМЕТКА, СЕМЕЙСТВО, ПРЕДЕЛ_СТОРОНЫ, ПРЕДЕЛ_ПЛОЩАДИ,
};
if (typeof module !== 'undefined' && module.exports) module.exports = API;
if (typeof globalThis !== 'undefined') globalThis.TIMatrixPng = API;

})();
