/* =============================================================================
 * unsaved.js — кейс изменён и не выгружен
 * =============================================================================
 *
 * ЗАЧЕМ. Кейс живёт в профиле браузера. Сброс профиля, переустановка,
 * чужая машина, «почистил кэш» — и расследования нет. В описании честно
 * написано «выгружайте до закрытия», но полагаться на дисциплину здесь —
 * то же самое, что полагаться на память аналитика в конце смены, от чего
 * режим данных как раз и отказался.
 *
 * ПОЧЕМУ СЧИТАЕМ ПО ХРОНОЛОГИИ, А НЕ ЗАВОДИМ ФЛАГ. Отдельный флаг
 * «изменён» надо выставлять в каждом месте, где кейс меняется, и ровно
 * одно забытое место даёт молчаливый дефект: предупреждения нет, человек
 * считает, что всё выгружено. Хронология уже пишется сама и уже содержит
 * и изменения, и выгрузки. Считать по ней — значит не иметь второго
 * источника правды, который может разойтись с первым.
 *
 * Модуль чистый: на вход хронология, на выход факты. Ни DOM, ни storage.
 * ========================================================================== */

'use strict';

(function initUnsaved(глоб) {

/* События, после которых кейс отличается от последней выгрузки.
 * Список намеренно перечислительный, а не «всё, кроме экспорта»:
 * новое событие должно попадать сюда осознанно. Запись о запуске
 * плейбука или об открытии инструментов кейс не меняет — выгружать
 * заново из-за них нечего. */
const ИЗМЕНЕНИЯ = new Set([
  'case.started',
  'ioc.added',
  'ioc.removed',
  'verdict.set',
  'verdict.source',
  'note.set',
]);

const ВЫГРУЗКА = 'export.done';

const ЧАС = 3600 * 1000;

function мс(t) {
  const n = Date.parse(t || '');
  return Number.isFinite(n) ? n : null;
}

/**
 * Состояние кейса относительно последней выгрузки.
 *
 * @param {Array} хронология  события кейса, каждое с полями kind и t
 * @param {object} [опт]
 * @param {number} [опт.сейчас]  текущее время в мс (для проверок)
 * @returns {{изменён: boolean, измененийПослеВыгрузки: number,
 *            последнееИзменение: (number|null), последняяВыгрузка: (number|null),
 *            часовБезВыгрузки: (number|null)}}
 */
function состояние(хронология, опт = {}) {
  const сейчас = опт.сейчас || Date.now();
  let последнееИзменение = null;
  let последняяВыгрузка = null;

  for (const ev of Array.isArray(хронология) ? хронология : []) {
    const t = мс(ev && ev.t);
    if (t === null || !ev.kind) continue;
    if (ev.kind === ВЫГРУЗКА) {
      if (последняяВыгрузка === null || t > последняяВыгрузка) последняяВыгрузка = t;
    } else if (ИЗМЕНЕНИЯ.has(ev.kind)) {
      if (последнееИзменение === null || t > последнееИзменение) последнееИзменение = t;
    }
  }

  /* Изменения, случившиеся ПОСЛЕ последней выгрузки. Считаются отдельно
   * от флага: «тридцать изменений без выгрузки» и «одно» — разные поводы
   * беспокоить человека. */
  let измененийПослеВыгрузки = 0;
  for (const ev of Array.isArray(хронология) ? хронология : []) {
    const t = мс(ev && ev.t);
    if (t === null || !ИЗМЕНЕНИЯ.has(ev.kind)) continue;
    if (последняяВыгрузка === null || t > последняяВыгрузка) измененийПослеВыгрузки++;
  }

  const изменён = измененийПослеВыгрузки > 0;
  /* Отсчёт ведётся от ПЕРВОГО невыгруженного изменения, а не от
   * последнего: кейс, который правят каждые десять минут весь день,
   * не выгружался столько же, сколько и забытый. Считать от последнего
   * изменения значило бы никогда не предупредить именно о нём. */
  let первоеБезВыгрузки = null;
  for (const ev of Array.isArray(хронология) ? хронология : []) {
    const t = мс(ev && ev.t);
    if (t === null || !ИЗМЕНЕНИЯ.has(ev.kind)) continue;
    if (последняяВыгрузка !== null && t <= последняяВыгрузка) continue;
    if (первоеБезВыгрузки === null || t < первоеБезВыгрузки) первоеБезВыгрузки = t;
  }

  return {
    изменён,
    измененийПослеВыгрузки,
    последнееИзменение,
    последняяВыгрузка,
    часовБезВыгрузки: первоеБезВыгрузки === null
      ? null : Math.max(0, (сейчас - первоеБезВыгрузки) / ЧАС),
  };
}

/**
 * Нужно ли показывать напоминание и каким текстом.
 *
 * Порог в часах — не украшение: предупреждать о кейсе, которому две
 * минуты, значит приучить закрывать предупреждение не читая.
 *
 * @returns {{показывать: boolean, текст: string, срочно: boolean}}
 */
function напоминание(хронология, опт = {}) {
  const порогЧасов = опт.порогЧасов ?? 2;
  const порогИзменений = опт.порогИзменений ?? 20;
  const с = состояние(хронология, опт);
  if (!с.изменён) return { показывать: false, текст: '', срочно: false };

  const часов = с.часовБезВыгрузки || 0;
  const давно = часов >= порогЧасов;
  const много = с.измененийПослеВыгрузки >= порогИзменений;
  if (!давно && !много) return { показывать: false, текст: '', срочно: false };

  const целых = Math.floor(часов);
  const когда = с.последняяВыгрузка === null
    ? T('кейс ни разу не выгружался')
    : (целых >= 1 ? T`с последней выгрузки прошло ${целых} ч`
                  : T('с последней выгрузки прошло меньше часа'));
  return {
    показывать: true,
    срочно: часов >= 24 || с.измененийПослеВыгрузки >= 50,
    текст: T`${когда}, изменений с тех пор: ${с.измененийПослеВыгрузки}. `
      + T('Кейс живёт в профиле браузера — выгрузите его, пока он есть.'),
  };
}

const API = { состояние, напоминание, ИЗМЕНЕНИЯ, ВЫГРУЗКА };
глоб.TIUnsaved = API;
if (typeof module !== 'undefined' && module.exports) module.exports = API;

})(typeof self !== 'undefined' ? self
   : (typeof globalThis !== 'undefined' ? globalThis : this));
