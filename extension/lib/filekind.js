/*
 * extension/lib/filekind.js — что за файл принёс аналитик.
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ
 * ---------------------------
 * Разбор читает файл КАК ТЕКСТ. Для txt, csv, json, eml, har это верно,
 * для PNG, docx, zip и exe — нет: `f.text()` отдаёт байты, истолкованные
 * как UTF-8, то есть мусор.
 *
 * Мусор не остаётся мусором. Он попадает в поле ввода, разбирается
 * обычным парсером, и в выдаче появляются «индикаторы», собранные
 * из случайных байтов. На обычном скриншоте 900×520 это дало
 * 149 записей в триаже и один «индикатор» — цифры, за которыми
 * не стоит ничего.
 *
 * Это худший класс дефекта в этом продукте: ответ выглядит работой.
 * Аналитик видит непустую выдачу и не видит причины ей не верить.
 *
 * ПОЧЕМУ ПО БАЙТАМ, А НЕ ПО РАСШИРЕНИЮ И НЕ ПО f.type
 * ---------------------------------------------------
 * Расширение врёт: письмо приезжает как .txt, HAR как .json, а из
 * тикета файл приходит вовсе без расширения — по этой причине письмо
 * и HAR здесь и опознаются по содержимому.
 *
 * `File.type` врёт иначе: он пуст для файла, перетащенного из архива
 * или из некоторых почтовых клиентов, и его же подставляет атрибут
 * accept, который человек обходит выбором «все файлы» в диалоге.
 *
 * Байты не врут. Поэтому решение принимается по сигнатуре, а имя
 * и тип используются только чтобы объяснить отказ человеку.
 */
'use strict';

(function initFileKindModule() {

if (typeof globalThis !== 'undefined' && globalThis.TIFileKind) return;

/* Сигнатуры. Смещение, байты, что это.
 *
 * Список короткий намеренно: сюда входит то, что аналитик реально
 * приносит по ошибке вместо текста. Полный определитель форматов
 * здесь не нужен — всё незнакомое и двоичное отсеет проверка ниже. */
const СИГНАТУРЫ = [
  { вид: 'pdf',   сдвиг: 0, байты: [0x25, 0x50, 0x44, 0x46, 0x2d], имя: 'PDF' },           // %PDF-
  { вид: 'image', сдвиг: 0, байты: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], имя: 'PNG' },
  { вид: 'image', сдвиг: 0, байты: [0xff, 0xd8, 0xff], имя: 'JPEG' },
  { вид: 'image', сдвиг: 0, байты: [0x47, 0x49, 0x46, 0x38], имя: 'GIF' },
  { вид: 'image', сдвиг: 0, байты: [0x42, 0x4d], имя: 'BMP' },
  /* WEBP: RIFF....WEBP — четыре байта размера между ними. */
  { вид: 'image', сдвиг: 8, байты: [0x57, 0x45, 0x42, 0x50], имя: 'WebP',
    доп: { сдвиг: 0, байты: [0x52, 0x49, 0x46, 0x46] } },
  /* ZIP-контейнеры: docx, xlsx, pptx, odt, jar и сам zip.
   * Для разбора это двоичный файл: внутри сжатый XML, и `f.text()`
   * отдаёт от него шум. */
  { вид: 'archive', сдвиг: 0, байты: [0x50, 0x4b, 0x03, 0x04], имя: T('ZIP или документ Office') },
  { вид: 'archive', сдвиг: 0, байты: [0x50, 0x4b, 0x05, 0x06], имя: T('пустой ZIP') },
  { вид: 'archive', сдвиг: 0, байты: [0x52, 0x61, 0x72, 0x21], имя: 'RAR' },
  { вид: 'archive', сдвиг: 0, байты: [0x37, 0x7a, 0xbc, 0xaf], имя: '7z' },
  { вид: 'archive', сдвиг: 0, байты: [0x1f, 0x8b], имя: 'gzip' },
  { вид: 'binary',  сдвиг: 0, байты: [0x4d, 0x5a], имя: T('исполняемый файл Windows') },        // MZ
  { вид: 'binary',  сдвиг: 0, байты: [0x7f, 0x45, 0x4c, 0x46], имя: T('исполняемый файл ELF') },
  { вид: 'binary',  сдвиг: 0, байты: [0xd0, 0xcf, 0x11, 0xe0], имя: T('старый документ Office') },
];

function совпало(байты, правило) {
  const пров = (с, б) => {
    if (байты.length < с + б.length) return false;
    for (let i = 0; i < б.length; i++) if (байты[с + i] !== б[i]) return false;
    return true;
  };
  if (!пров(правило.сдвиг, правило.байты)) return false;
  if (правило.доп && !пров(правило.доп.сдвиг, правило.доп.байты)) return false;
  return true;
}

/* Доля байтов, которых в текстовом файле быть не должно.
 *
 * Считаются управляющие символы, кроме перевода строки, возврата
 * каретки, табуляции и перевода страницы. Нулевой байт считается
 * отдельно: в тексте его не бывает вовсе, одного достаточно.
 *
 * Порог 10% — с запасом. У текста в любой кодировке доля таких байтов
 * близка к нулю; у сжатого содержимого — около четверти. Между этими
 * величинами есть куда поставить границу, не гадая. */
const ПОРОГ_МУСОРА = 0.10;

function мусорность(байты) {
  if (!байты || !байты.length) return { нулей: 0, доля: 0 };
  let нулей = 0, плохих = 0;
  for (const b of байты) {
    if (b === 0x00) { нулей++; плохих++; continue; }
    if (b < 0x09 || (b > 0x0d && b < 0x20) || b === 0x7f) плохих++;
  }
  return { нулей, доля: плохих / байты.length };
}

/**
 * Что за файл.
 *
 * @param {Uint8Array|number[]} голова  первые байты файла (хватает 512)
 * @param {string} имя                  имя файла — только для объяснения
 * @returns {{вид: string, формат: string, причина: string}}
 *   вид: 'text' | 'pdf' | 'image' | 'archive' | 'binary'
 */
function вид(голова, имя) {
  const байты = голова instanceof Uint8Array ? голова : Uint8Array.from(голова || []);
  const назв = String(имя || T('файл'));

  for (const правило of СИГНАТУРЫ) {
    if (!совпало(байты, правило)) continue;
    if (правило.вид === 'pdf') {
      return { вид: 'pdf', формат: 'PDF', причина: '' };
    }
    if (правило.вид === 'image') {
      return { вид: 'image', формат: правило.имя,
               причина: T`${назв} — это картинка (${правило.имя}). `
                      + T('Текста в ней нет: его надо распознать') };
    }
    return { вид: правило.вид, формат: правило.имя,
             причина: T`${назв} — это ${правило.имя}, а не текст. `
                    + T('Разбор читает файл как текст, и из такого файла ')
                    + T('получились бы «индикаторы», собранные из случайных байтов') };
  }

  /* Сигнатуры не хватило — смотрим на сами байты. Так отсеиваются
   * форматы, которых нет в списке: их будет больше, чем в списке,
   * и каждый следующий не должен требовать правки кода. */
  const { нулей, доля } = мусорность(байты);
  if (нулей > 0 || доля > ПОРОГ_МУСОРА) {
    return { вид: 'binary', формат: T('двоичный файл'),
             причина: T`${назв} — двоичный файл, а не текст`
                    + (нулей ? T(' (в первых байтах есть нулевой)') : '')
                    + T('. Разбор читает файл как текст, и из такого файла ')
                    + T('получились бы «индикаторы», собранные из случайных байтов') };
  }
  return { вид: 'text', формат: T('текст'), причина: '' };
}

/** Сколько байтов достаточно прочитать, чтобы решить. */
const НЮХ_БАЙТ = 512;

const API = { вид, мусорность, НЮХ_БАЙТ, ПОРОГ_МУСОРА, СИГНАТУРЫ };
if (typeof module !== 'undefined' && module.exports) module.exports = API;
if (typeof globalThis !== 'undefined') globalThis.TIFileKind = API;

})();
