/**
 * Разобрать то, что лежит в хранилище.
 *
 * Возвращает {настройки, замечания}. Замечания — не отладка: они
 * показываются человеку. Настройки могли приехать из старшей версии,
 * из чужого файла, из полуудачной записи — и «мы тут кое-что поправили
 * молча» это худший вариант из возможных.
 */
function нормализовать(сырое, сейчас = Date.now()) {
  const зам = [];
  const осн = поумолчанию(сейчас);

  if (сырое === null || сырое === undefined) return { настройки: осн, замечания: зам };
  if (typeof сырое !== 'object' || Array.isArray(сырое)) {
    зам.push(T('Настройки в хранилище не похожи на настройки — взяты значения по умолчанию.'));
    return { настройки: осн, замечания: зам };
  }

  const версия = Number(сырое.версия);
  if (Number.isFinite(версия) && версия > ВЕРСИЯ) {
    зам.push(T`Настройки сохранены версией ${версия}, эта понимает ${ВЕРСИЯ}. `
           + T('Неизвестные поля отброшены.'));
  }

  const функции = {};
  const сыр = (сырое.функции && typeof сырое.функции === 'object') ? сырое.функции : {};
  for (const ф of ФУНКЦИИ) {
    if (ф.ядро) {
      if (ф.id in сыр && сыр[ф.id] !== true) {
        зам.push(T`«${ф.имя}» выключить нельзя: это ядро рабочего места. Оставлено включённым.`);
      }
      функции[ф.id] = true;
      continue;
    }
    const v = сыр[ф.id];
    if (v === undefined) {
      /* Функция появилась позже, чем сохранялись настройки. Берём
       * значение из пресета — а не «выключено»: иначе каждое обновление
       * тихо прятало бы новое от тех, кто настроек не открывает. */
      const п = ПРЕСЕТ_ПО_ID.get(сырое.пресет) || null;
      функции[ф.id] = п ? п.функции.includes(ф.id) : осн.функции[ф.id];
      continue;
    }
    if (typeof v !== 'boolean') {
      зам.push(T`Значение «${ф.имя}» не да/нет — взято включённое состояние.`);
      функции[ф.id] = !!v;
      continue;
    }
    функции[ф.id] = v;
  }

  const лишние = Object.keys(сыр).filter((k) => !ПО_ID.has(k));
  if (лишние.length) {
    зам.push(T`Неизвестные функции отброшены: ${лишние.slice(0, 6).join(', ')}`
           + (лишние.length > 6 ? T` и ещё ${лишние.length - 6}` : '') + '.');
  }

  let пресет = String(сырое.пресет || '');
  if (пресет !== СВОЙ && !ПРЕСЕТ_ПО_ID.has(пресет)) {
    if (пресет) зам.push(T`Пресет «${пресет}» неизвестен — состав определён по галочкам.`);
    пресет = СВОЙ;
  }
  /* Пресет и галочки могли разойтись: настройки правили руками, файлом,
   * другой версией. Верим галочкам — они и есть состав. */
  if (пресет !== СВОЙ && !совпадаетСПресетом(функции, пресет)) пресет = СВОЙ;
  if (пресет === СВОЙ) {
    const найден = ПРЕСЕТЫ.find((п) => совпадаетСПресетом(функции, п.id));
    if (найден) пресет = найден.id;
  }

  return {
    настройки: {
      версия: ВЕРСИЯ,
      пресет,
      функции,
      первыйЗапуск: сырое.первыйЗапуск === true,
      подсказкаПоказана: сырое.подсказкаПоказана === true,
      учёт: сырое.учёт !== false,
      создано: Number.isFinite(Number(сырое.создано)) ? Number(сырое.создано) : сейчас,
      счётчики: чистыеСчётчики(сырое.счётчики, зам),
    },
    замечания: зам,
  };
}

function чистыеСчётчики(сырое, зам) {
  const out = {};
  if (!сырое || typeof сырое !== 'object' || Array.isArray(сырое)) return out;
  let битых = 0;
  for (const [id, v] of Object.entries(сырое)) {
    if (!ПО_ID.has(id)) { битых++; continue; }
    const раз = Number(v && v.раз);
    const последний = Number(v && v.последний);
    if (!Number.isFinite(раз) || раз < 0) { битых++; continue; }
    out[id] = {
      раз: Math.min(Math.floor(раз), 1e9),
      последний: Number.isFinite(последний) && последний > 0 ? последний : 0,
    };
  }
  if (битых && зам) зам.push(T`Счётчиков использования отброшено: ${битых}.`);
  return out;
}

function совпадаетСПресетом(функции, имяПресета) {
  const п = ПРЕСЕТ_ПО_ID.get(имяПресета);
  if (!п) return false;
  return НАСТРАИВАЕМЫЕ.every((id) => !!функции[id] === п.функции.includes(id));
}

/**
 * Применить пресет, НЕ ТРОГАЯ ничего, кроме состава.
 *
 * Счётчики, отметка первого запуска и согласие на учёт переживают смену
 * пресета; кейсы, хронология и матрица лежат в других ключах хранилища
 * и этой функции не видны вовсе. Смена пресета — это изменение вида,
 * а не сброс работы.
 */
function применитьПресет(наст, имя, сейчас = Date.now()) {
  const п = ПРЕСЕТ_ПО_ID.get(имя);
  if (!п) return { ...наст };
  const функции = {};
  for (const ф of ФУНКЦИИ) функции[ф.id] = ф.ядро ? true : п.функции.includes(ф.id);
  return { ...наст, версия: ВЕРСИЯ, пресет: п.id, функции, изменено: сейчас };
}

/** Переключить одну функцию. Ядро не трогается; пресет становится «свой». */
function переключить(наст, id, значение, сейчас = Date.now()) {
  const ф = ПО_ID.get(id);
  if (!ф || ф.ядро) return { ...наст };
  const функции = { ...наст.функции, [id]: !!значение };
  const найден = ПРЕСЕТЫ.find((п) => совпадаетСПресетом(функции, п.id));
  return { ...наст, функции, пресет: найден ? найден.id : СВОЙ, изменено: сейчас };
}

/**
 * Включена ли функция С УЧЁТОМ зависимостей.
 *
 * Зависимость не записывается в хранилище: если выключить вкладку ATT&CK,
 * а потом включить обратно, «матрица картинкой» должна вернуться в том
 * состоянии, в каком была. Затирать чужую галочку ради производной —
 * потеря настройки, которую человек не делал.
 */
function включено(наст, id) {
  const ф = ПО_ID.get(id);
  if (!ф) return false;
  if (ф.ядро) return true;
  if (!наст || !наст.функции || наст.функции[id] !== true) return false;
  if (ф.зависит) return включено(наст, ф.зависит);
  return true;
}

/** Что показывать: вкладки и узлы. Готовый ответ для интерфейса. */
function видимость(наст) {
  const вкладки = {};
  const узлы = {};
  for (const ф of ФУНКЦИИ) {
    const вкл = включено(наст, ф.id);
    if (ф.вкладка) вкладки[ф.вкладка] = вкл;
    for (const с of ф.узлы || []) узлы[с] = вкл;
  }
  return { вкладки, узлы };
}

/** Выключенные функции — для палитры: найти и включить, не идя в настройки. */
function выключенные(наст) {
  return ФУНКЦИИ.filter((ф) => !ф.ядро && !включено(наст, ф.id));
}

/* ------------------------------------------------------ УЧЁТ ИСПОЛЬЗОВАНИЯ -
 *
 * Считается ФАКТ применения, а не подробности: идентификатор функции,
 * сколько раз и когда в последний раз. Ни индикаторов, ни имён файлов,
 * ни названий кейсов — иначе счётчики превратились бы во второй журнал
 * расследования, который никто не собирался заводить.
 *
 * Зачем вообще: решение «что убрать из интерфейса» иначе принимается
 * по впечатлениям. Через месяц работы видно, чем не пользовались ни разу,
 * — и это разговор о продукте, а не о вкусах.
 * -------------------------------------------------------------------------- */
function отметить(наст, id, сейчас = Date.now()) {
  if (!ПО_ID.has(id)) return наст;          // чужой ключ в счётчики не попадает
  if (!наст || наст.учёт === false) return наст;
  const было = (наст.счётчики && наст.счётчики[id]) || { раз: 0, последний: 0 };
  return {
    ...наст,
    счётчики: { ...наст.счётчики, [id]: { раз: было.раз + 1, последний: сейчас } },
  };
}

function отчётОбИспользовании(наст, сейчас = Date.now()) {
  const с = (наст && наст.счётчики) || {};
  return ФУНКЦИИ.filter((ф) => !ф.ядро).map((ф) => {
    const зап = с[ф.id] || { раз: 0, последний: 0 };
    return {
      id: ф.id,
      имя: ф.имя,
      кат: ф.кат,
      включена: включено(наст, ф.id),
      раз: зап.раз,
      последний: зап.последний,
      днейБезДела: дниБезДела(наст, ф.id, сейчас),
    };
  }).sort((a, b) => b.раз - a.раз || a.имя.localeCompare(b.имя, 'ru'));
}

function дниБезДела(наст, id, сейчас = Date.now()) {
  const зап = (наст && наст.счётчики && наст.счётчики[id]) || null;
  const отсчёт = (зап && зап.последний) || (наст && наст.создано) || сейчас;
  return Math.max(0, Math.floor((сейчас - отсчёт) / ДЕНЬ));
}

/**
 * Забытое в обе стороны.
 *
 * «Включено и не используется» — кандидат на то, чтобы убрать с экрана:
 * это и есть борьба с перегрузкой, ради которой всё затевалось.
 *
 * «Выключено давно» — обратное напоминание. Функция не исчезла, её
 * по-прежнему гоняют проверки, и человек мог просто забыть, что она есть.
 *
 * Порог в днях, а не «месяц»: сменная работа, отпуска, длинные
 * расследования — календарный месяц тут ничего не значит.
 */
function забытые(наст, сейчас = Date.now(), опции = {}) {
  const порогВкл = Number(опции.днейВключена) > 0 ? Number(опции.днейВключена) : 30;
  const порогВыкл = Number(опции.днейВыключена) > 0 ? Number(опции.днейВыключена) : 90;
  const out = [];
  for (const ф of ФУНКЦИИ) {
    if (ф.ядро) continue;
    const дней = дниБезДела(наст, ф.id, сейчас);
    const вкл = включено(наст, ф.id);
    if (вкл && дней >= порогВкл) {
      out.push({ id: ф.id, имя: ф.имя, состояние: 'включена', дней,
                 совет: T('занимает место на экране — может, выключить') });
    } else if (!вкл && дней >= порогВыкл) {
      out.push({ id: ф.id, имя: ф.имя, состояние: 'выключена', дней,
                 совет: T('выключена давно — посмотрите, нужна ли она вам') });
    }
  }
  return out.sort((a, b) => b.дней - a.дней);
}

