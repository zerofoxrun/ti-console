/* Проверки unsaved.js.
 *
 * Модуль чистый, поэтому проверяется без браузера. Каждая проверка
 * здесь отвечает на вопрос «при каком состоянии хронологии человека
 * надо побеспокоить», и ошибка в любой из них выглядит одинаково:
 * предупреждения нет, кейс считается выгруженным.
 */
'use strict';

globalThis.T = (s, ...a) => (Array.isArray(s)
  ? s.raw.reduce((acc, ч, i) => acc + ч + (i < a.length ? a[i] : ''), '')
  : s);

const U = require('./unsaved.js');

let всего = 0;
let плохо = 0;
function check(имя, условие, деталь = '') {
  всего++;
  if (!условие) { плохо++; console.log(`ПЛОХО  ${имя}${деталь ? ' — ' + деталь : ''}`); }
}

const ЧАС = 3600 * 1000;
const T0 = Date.parse('2026-10-20T09:00:00Z');
const в = (мс) => new Date(мс).toISOString();

/* ------------------------------------------------- пустая хронология --- */
{
  const с = U.состояние([], { сейчас: T0 });
  check('пустая хронология — не изменён', с.изменён === false);
  check('пустая хронология — нечего считать', с.часовБезВыгрузки === null);
  check('не массив не роняет', U.состояние(null, { сейчас: T0 }).изменён === false);
  check('запись без kind игнорируется',
        U.состояние([{ t: в(T0) }], { сейчас: T0 }).изменён === false);
  check('запись без времени игнорируется',
        U.состояние([{ kind: 'ioc.added' }], { сейчас: T0 }).изменён === false);
}

/* ------------------------------------------------------ базовый случай -- */
{
  const хр = [
    { kind: 'case.started', t: в(T0 - 3 * ЧАС) },
    { kind: 'ioc.added', t: в(T0 - 2 * ЧАС) },
  ];
  const с = U.состояние(хр, { сейчас: T0 });
  check('изменения без выгрузки — изменён', с.изменён === true);
  check('считаются все изменения', с.измененийПослеВыгрузки === 2,
        String(с.измененийПослеВыгрузки));
  check('выгрузки не было', с.последняяВыгрузка === null);
  /* Отсчёт от ПЕРВОГО невыгруженного изменения: кейс не выгружался
   * три часа, а не два. */
  check('часы считаются от первого изменения',
        Math.round(с.часовБезВыгрузки) === 3, String(с.часовБезВыгрузки));
}

/* ---------------------------------------------------- выгрузка закрывает */
{
  const хр = [
    { kind: 'ioc.added', t: в(T0 - 5 * ЧАС) },
    { kind: 'export.done', t: в(T0 - 4 * ЧАС) },
  ];
  const с = U.состояние(хр, { сейчас: T0 });
  check('после выгрузки не изменён', с.изменён === false);
  check('после выгрузки счётчик ноль', с.измененийПослеВыгрузки === 0);
  check('после выгрузки часов нет', с.часовБезВыгрузки === null);
}

/* ----------------------------------- изменение ПОСЛЕ выгрузки считается - */
{
  const хр = [
    { kind: 'ioc.added', t: в(T0 - 5 * ЧАС) },
    { kind: 'export.done', t: в(T0 - 4 * ЧАС) },
    { kind: 'verdict.set', t: в(T0 - 1 * ЧАС) },
  ];
  const с = U.состояние(хр, { сейчас: T0 });
  check('изменение после выгрузки — изменён', с.изменён === true);
  check('считается только то, что после выгрузки', с.измененийПослеВыгрузки === 1,
        String(с.измененийПослеВыгрузки));
  check('часы от изменения после выгрузки',
        Math.round(с.часовБезВыгрузки) === 1, String(с.часовБезВыгрузки));
}

/* ------------------------- события, которые кейс не меняют, не считаются - */
{
  const хр = [
    { kind: 'ioc.added', t: в(T0 - 5 * ЧАС) },
    { kind: 'export.done', t: в(T0 - 4 * ЧАС) },
    { kind: 'tools.opened', t: в(T0 - 3 * ЧАС) },
    { kind: 'playbook.run', t: в(T0 - 2 * ЧАС) },
    { kind: 'source.parsed', t: в(T0 - 1 * ЧАС) },
  ];
  const с = U.состояние(хр, { сейчас: T0 });
  check('открытие инструментов не делает кейс изменённым', с.изменён === false,
        JSON.stringify(с));
}

/* ----------------------------------- порядок записей не важен ----------- */
{
  const поПорядку = [
    { kind: 'ioc.added', t: в(T0 - 5 * ЧАС) },
    { kind: 'export.done', t: в(T0 - 4 * ЧАС) },
    { kind: 'note.set', t: в(T0 - 3 * ЧАС) },
  ];
  const вразнобой = [поПорядку[2], поПорядку[0], поПорядку[1]];
  const а = U.состояние(поПорядку, { сейчас: T0 });
  const б = U.состояние(вразнобой, { сейчас: T0 });
  check('перемешанная хронология даёт тот же ответ',
        JSON.stringify(а) === JSON.stringify(б), JSON.stringify(б));
}

/* ------------------------------------------------------- напоминание ---- */
{
  const свежий = [{ kind: 'ioc.added', t: в(T0 - 10 * 60 * 1000) }];
  check('десятиминутный кейс не беспокоит',
        U.напоминание(свежий, { сейчас: T0 }).показывать === false);

  const старый = [{ kind: 'ioc.added', t: в(T0 - 3 * ЧАС) }];
  const н = U.напоминание(старый, { сейчас: T0 });
  check('трёхчасовой кейс беспокоит', н.показывать === true);
  check('в тексте сказано, что выгрузки не было', /ни разу/.test(н.текст), н.текст);
  check('три часа — ещё не срочно', н.срочно === false);

  const сутки = [{ kind: 'ioc.added', t: в(T0 - 30 * ЧАС) }];
  check('суточный кейс срочен', U.напоминание(сутки, { сейчас: T0 }).срочно === true);

  /* Много правок за короткое время — тоже повод: аналитик увлёкся
   * и точно не выгружал. */
  const много = [];
  for (let i = 0; i < 25; i++) много.push({ kind: 'ioc.added', t: в(T0 - i * 60 * 1000) });
  const нм = U.напоминание(много, { сейчас: T0 });
  check('двадцать пять правок за полчаса беспокоят', нм.показывать === true,
        JSON.stringify(нм));

  const выгружен = [
    { kind: 'ioc.added', t: в(T0 - 30 * ЧАС) },
    { kind: 'export.done', t: в(T0 - 29 * ЧАС) },
  ];
  check('выгруженный старый кейс не беспокоит',
        U.напоминание(выгружен, { сейчас: T0 }).показывать === false);
}

console.log(плохо ? `ПЛОХО: ${плохо} из ${всего}` : `unsaved.js: ${всего} проверок, все прошли`);
process.exit(плохо ? 1 : 0);
