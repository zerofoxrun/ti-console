/* =============================================================================
 * pivot.js — что можно сделать с одним значением
 * =============================================================================
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
 * ----------------------
 * Вопрос «какие сервисы показать для этого индикатора» задаётся теперь
 * из трёх мест: вкладка консоли, боковая панель и карточка на странице
 * (0.57.0). Ответ на него — это не список ссылок, а ГЕЙТ: сюда входят
 * режим клиентских данных, свои и клиентские диапазоны и отметка
 * «платно». Три копии гейта разойдутся, и разойдутся молча: карточка
 * на чужой странице покажет публичный сервис там, где консоль его
 * закрыла, и аналитик отправит адрес заказчика в VirusTotal одним
 * кликом, будучи уверенным, что расширение это запрещает.
 *
 * Поэтому решение живёт здесь, в чистых функциях без DOM, и проверяется
 * без браузера.
 *
 * ЗАКРЫТОЕ НАЗЫВАЕТСЯ
 * -------------------
 * `подобрать` возвращает не только то, что можно, но и то, что закрыто,
 * с причиной. Короткий список без объяснения читается как «для этого
 * типа у нас ничего нет», и аналитик идёт искать сервис в браузере —
 * то есть ровно туда, откуда его уводили.
 * ========================================================================== */
(function () {
'use strict';

/**
 * Подставить значение в шаблон адреса сервиса.
 *
 * Пустое значение — это клик по инструменту без выбранного индикатора.
 * Подстановка пустой строки давала обрубок вида
 * `https://www.abuseipdb.com/check/` — страницу, которой нет: инструмент
 * «не открылся», хотя вкладка открылась. Поэтому для пустого значения
 * открывается корень сайта.
 */
function ссылка(tool, значение) {
  const url = String((tool && tool.url) || '');
  const v = String(значение == null ? '' : значение);
  if (!v) {
    if (/\{\{ioc(?:_raw)?\}\}/.test(url)) {
      try { return new URL(url).origin + '/'; } catch (_) { /* ниже */ }
    }
  }
  return url
    .replace(/\{\{ioc\}\}/g, encodeURIComponent(v))
    .replace(/\{\{ioc_raw\}\}/g, v);
}

/* Причины отказа. Строками, а не кодами: их показывают человеку,
 * и перевод кода в текст в трёх местах — это три разных текста. */
const ПРИЧИНЫ = {
  режим: T('закрыт режимом клиентских данных'),
  свой: T('это наш или клиентский адрес — в публичный сервис он не уходит'),
  платно: T('нужен платный тариф (скрыто настройкой)'),
};

/**
 * Что можно сделать со значением прямо сейчас.
 *
 * @param {object} п
 * @param {string} п.значение     само значение индикатора
 * @param {string} п.тип          тип из ioc.js (ipv4, domain, …)
 * @param {object} п.реестр       tools.json: { tools: [...] }
 * @param {string} п.tlp          'public' | 'client'
 * @param {object} п.свои         результат TIOwnRanges.разобрать (может быть null)
 * @param {boolean} п.скрытьПлатные
 * @param {object} п.ownranges    модуль TIOwnRanges (внедряется ради тестов)
 * @returns {{значение,тип,инструменты,закрыто,свой,дефанг,всего}}
 */
function подобрать(п) {
  const значение = String((п && п.значение) || '');
  const тип = String((п && п.тип) || '');
  const реестр = (п && п.реестр) || {};
  const tlp = (п && п.tlp) === 'client' ? 'client' : 'public';
  const свои = (п && п.свои) || null;
  const скрытьПлатные = !!(п && п.скрытьПлатные);
  const OR = (п && п.ownranges) || (typeof globalThis !== 'undefined' && globalThis.TIOwnRanges);

  const все = Array.isArray(реестр.tools) ? реестр.tools : [];
  const подходящие = все.filter((t) => Array.isArray(t.types) && t.types.includes(тип));

  const инструменты = [];
  const закрыто = [];
  /* Значение проверяется на принадлежность своим диапазонам ОДИН раз,
   * а не на каждый сервис: ответ от сервиса не зависит. */
  const чьё = (OR && свои && значение)
    ? OR.чей({ type: тип, value: значение }, свои)
    : null;

  for (const t of подходящие) {
    if (tlp === 'client' && t.exposure === 'public') {
      закрыто.push({ имя: t.name, причина: ПРИЧИНЫ.режим });
      continue;
    }
    /* Свой адрес не уходит в публичный сервис даже в публичном режиме:
     * запрос к VirusTotal по адресу заказчика — это раскрытие адреса
     * заказчика, независимо от того, какой режим выбран на экране. */
    if (чьё && t.exposure === 'public') {
      закрыто.push({ имя: t.name, причина: ПРИЧИНЫ.свой });
      continue;
    }
    if (скрытьПлатные && t.pricing === 'paid') {
      закрыто.push({ имя: t.name, причина: ПРИЧИНЫ.платно });
      continue;
    }
    инструменты.push({
      id: t.id,
      имя: t.name,
      url: ссылка(t, значение),
      exposure: t.exposure,
      платно: t.pricing === 'paid',
      регистрация: t.pricing === 'free-account',
    });
  }

  return {
    значение,
    тип,
    инструменты,
    закрыто,
    свой: чьё ? (OR.подпись ? OR.подпись(чьё) : T('наш диапазон')) : '',
    всего: подходящие.length,
  };
}

/** Короткая строка о закрытом — для места, где список не помещается. */
function строкаОЗакрытом(закрыто) {
  if (!закрыто || !закрыто.length) return '';
  const поПричинам = new Map();
  for (const з of закрыто) поПричинам.set(з.причина, (поПричинам.get(з.причина) || 0) + 1);
  return [...поПричинам].map(([п, n]) => `${n} ${п}`).join(' · ');
}

const API = { ссылка, подобрать, строкаОЗакрытом, ПРИЧИНЫ };
if (typeof module !== 'undefined' && module.exports) module.exports = API;
if (typeof globalThis !== 'undefined') globalThis.TIPivot = API;

})();
