/* =============================================================================
 * myplaybooks.js — «Мои проверки»: один набор на все типы индикаторов
 * =============================================================================
 *
 * ЗАЧЕМ. Аналитик проверяет индикатор одними и теми же сервисами. Пока
 * список нельзя задать, он либо открывает лишнее, либо держит десяток
 * вкладок вручную — с этого и начался отзыв, ради которого всё это.
 *
 * ПОЧЕМУ НАБОР ОДИН, А НЕ ШЕСТЬ ПО ТИПАМ
 * -------------------------------------
 * В поставке наборы были типизированы: «фишинговый домен»,
 * «подозрительный адрес», «хеш». Для поставки это правильно, для своей
 * настройки оказалось лишней работой: человек не хочет шесть раз
 * отвечать на вопрос «а для каких типов», он хочет один раз перечислить
 * сервисы, которыми пользуется.
 *
 * Разбивка по типам никуда не делась — она перестала быть ручной.
 * Набор применим к тому типу, с которым работает хоть один его сервис,
 * а при открытии берутся только подходящие шаги: для IPv4 сетевые
 * сервисы, для SHA-256 песочницы. Список при этом один.
 *
 * ЦЕНА ЭТОГО РЕШЕНИЯ, ЧЕСТНО
 * --------------------------
 * Шесть курируемых списков нельзя свести в один плоский без потери
 * курирования: объединение всех шести даёт по восемнадцать сервисов
 * на IPv4 и на домен вместо одиннадцати и восьми. Поэтому набор по
 * умолчанию ПУСТ, а не заполнен объединением: расширение, которое
 * сразу после установки открывает восемнадцать вкладок по одному
 * нажатию, — это не удобство. Заполнить по встроенным последовательностям
 * можно одной кнопкой, и тогда это решение человека, а не наше.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ
 * -------------------------
 * Набор не задаёт сервису exposure и не создаёт сервисов — он выбирает
 * их из реестра по id. Иначе настройка стала бы способом объявить
 * публичный сервис внутренним и обойти TLP-гейт, то есть ровно то,
 * против чего гейт стоит. Планирование шагов целиком в playbook.js:
 * свой набор проходит тот же planPlaybook, и гейт для него не мягче.
 *
 * Модуль чистый: на вход данные, на выход данные. Ни DOM, ни storage.
 * ========================================================================== */

'use strict';

(function initMyPlaybooks(глоб) {

const КЛЮЧ = 'ti_playbooks';
const ВЕРСИЯ = 2;

/* Идентификатор нужен не для выбора между наборами — он один, — а для
 * хронологии и отчёта: запись «запущен набор» должна чем-то называться
 * и не совпадать с идентификаторами встроенных последовательностей,
 * которые остались в реестре как заготовка. */
const ID = 'мои-проверки';
const ИМЯ_ПО_УМОЛЧАНИЮ = 'Мои проверки';

function пусто() {
  return { версия: ВЕРСИЯ, набор: { name: '', steps: [] } };
}

function строка(v) {
  return typeof v === 'string' ? v.trim() : '';
}

function массивСтрок(v) {
  if (!Array.isArray(v)) return [];
  const out = [];
  for (const x of v) {
    const s = строка(x);
    if (s && !out.includes(s)) out.push(s);
  }
  return out;
}

/**
 * Привести прочитанное из хранилища к рабочему виду.
 *
 * ВСЁ ОТБРОШЕННОЕ НАЗЫВАЕТСЯ. Запись, которую молча выкинули, выглядит
 * как запись, которая работает: человек видит в файле список сервисов,
 * а на экране пусто, и считает, что настройка не сохранилась.
 *
 * Неизвестный id сервиса здесь НЕ вычищается: он останется в наборе,
 * попадёт в проверку как ошибка и будет назван при открытии как
 * «инструмента нет в реестре». Вычистить молча — значит сделать набор
 * короче, не сказав об этом.
 *
 * @returns {{хранилище: object, замечания: string[]}}
 */
function нормализовать(сырое) {
  const зам = [];
  const out = пусто();
  if (сырое === null || сырое === undefined) return { хранилище: out, замечания: зам };
  if (typeof сырое !== 'object' || Array.isArray(сырое)) {
    зам.push(T('Свои проверки прочитать не удалось — взят пустой список.'));
    return { хранилище: out, замечания: зам };
  }

  const версия = Number(сырое.версия);
  if (Number.isFinite(версия) && версия > ВЕРСИЯ) {
    зам.push(T`Свои проверки сохранены версией ${версия}, эта понимает ${ВЕРСИЯ}. `
           + T('Неизвестные поля отброшены.'));
  }

  /* ПЕРЕНОС СО СТАРОГО ВИДА (версия 1), где наборов было несколько.
   * Берётся общий набор, а если его не было — первый по счёту: он
   * и был тем, что человек настраивал. Остальные не теряются молча,
   * а называются числом: «было пять, остался один» — это то, что надо
   * узнать сразу, а не при первом разборе. */
  if (!сырое.набор && Array.isArray(сырое.свои)) {
    const свои = сырое.свои.filter((p) => p && typeof p === 'object');
    const взять = свои.find((p) => строка(p.id) === ID) || свои[0] || null;
    if (взять) {
      out.набор = {
        name: строка(взять.name) || ИМЯ_ПО_УМОЛЧАНИЮ,
        steps: массивСтрок(взять.steps),
      };
    }
    if (свои.length > 1) {
      зам.push(T`Наборы под отдельные типы больше не настраиваются. `
             + T`Оставлен один список, остальных записей было: ${свои.length - 1}.`);
    }
    return { хранилище: out, замечания: зам };
  }

  const н = сырое.набор;
  if (н && typeof н === 'object' && !Array.isArray(н)) {
    out.набор = { name: строка(н.name), steps: массивСтрок(н.steps) };
  }
  return { хранилище: out, замечания: зам };
}

/** Типы набора: объединение типов его сервисов. */
function типыПоСоставу(steps, tools) {
  const byId = new Map((tools || []).map((t) => [t.id, t]));
  const out = [];
  for (const id of Array.isArray(steps) ? steps : []) {
    const t = byId.get(id);
    for (const тип of (t && t.types) || []) if (!out.includes(тип)) out.push(тип);
  }
  return out;
}

/**
 * Набор в том виде, в каком его ждёт planPlaybook, или null.
 *
 * null означает «предлагать нечего»: набор не настроен либо ни один
 * его сервис не нашёлся в реестре. Кнопка «нечего открывать» — это шум,
 * а не информация.
 *
 * Без реестра типы считать не из чего, и набор не отдаётся: лучше не
 * предложить, чем предложить и открыть не то.
 */
function набор(хранилище, tools) {
  const х = нормализовать(хранилище).хранилище;
  const steps = массивСтрок(х.набор.steps);
  if (!steps.length) return null;
  const types = типыПоСоставу(steps, tools);
  if (!types.length) return null;
  return {
    id: ID,
    name: строка(х.набор.name) || T(ИМЯ_ПО_УМОЛЧАНИЮ),
    types,
    steps,
    свой: true,
  };
}

/** Набор одним списком — для мест, которые раньше перебирали плейбуки. */
function список(хранилище, tools) {
  const н = набор(хранилище, tools);
  return н ? [н] : [];
}

/* -------------------------------------------------------- ПРОВЕРКА -------
 *
 * Та же логика, что validatePlaybooks в playbook.js гоняет по реестру
 * в CI, но в момент сохранения. Набор, составленный с ошибкой, ведёт
 * себя тихо: шаг молча выпадает при открытии, аналитик считает проверку
 * сделанной, и в отчёте это выглядит именно так.
 *
 * Ошибки запрещают сохранение, предупреждения — нет: «в клиентском
 * режиме не останется шагов» бывает осознанным решением.
 * ------------------------------------------------------------------------ */
function проверить(что, tools) {
  const ошибки = [];
  const предупреждения = [];
  const byId = new Map((tools || []).map((t) => [t.id, t]));
  const steps = Array.isArray(что && что.steps)
    ? что.steps.map(строка).filter(Boolean) : [];

  if (!строка(что && что.name)) ошибки.push(T('Нет названия.'));
  if (!steps.length) ошибки.push(T('Не выбран ни один сервис.'));

  const встречен = new Set();
  for (const id of steps) {
    if (встречен.has(id)) { ошибки.push(T`Сервис встречается дважды: ${id}.`); continue; }
    встречен.add(id);
    if (!byId.get(id)) ошибки.push(T`В реестре нет сервиса ${id}.`);
  }

  const выживут = steps.filter((id) => byId.get(id) && byId.get(id).exposure !== 'public');
  if (steps.length && !выживут.length) {
    предупреждения.push(T('В режиме клиентских данных не останется ни одного шага: '
                        + 'все выбранные сервисы публичные.'));
  }

  /* Длинный список — не ошибка, но знать о последствии надо ДО того,
   * как по одному нажатию откроется двадцать вкладок. Считается по
   * самому населённому типу, а не по длине списка: в списке из сорока
   * сервисов по IPv4 может работать восемь. */
  const поТипам = {};
  for (const id of steps) {
    const t = byId.get(id);
    for (const тип of (t && t.types) || []) поТипам[тип] = (поТипам[тип] || 0) + 1;
  }
  const макс = Object.entries(поТипам).sort((a, b) => b[1] - a[1])[0];
  if (макс && макс[1] > 15) {
    предупреждения.push(T`Самый длинный разбор — ${макс[1]} вкладок за одно нажатие `
                      + T`(тип ${макс[0]}). Переспроса нет: откроются все сразу.`);
  }
  return { ошибки, предупреждения };
}

/** Записать набор. Возвращает НОВОЕ хранилище. */
function сохранить(хранилище, что) {
  const х = нормализовать(хранилище).хранилище;
  х.набор = {
    name: строка(что && что.name),
    steps: массивСтрок(что && что.steps),
  };
  return х;
}

/** Очистить набор целиком. Отдельное действие, не побочный эффект. */
function очистить() {
  return пусто();
}

/**
 * Состав по встроенным последовательностям из реестра.
 *
 * Это ЗАГОТОВКА, а не значение по умолчанию: подставляется только по
 * нажатию. Объединение шести курируемых списков даёт восемнадцать
 * сервисов на IPv4 — больше, чем было в любом из них, — и навязывать
 * это новому пользователю нельзя.
 */
function поВстроенным(встроенные) {
  const out = [];
  for (const pb of Array.isArray(встроенные) ? встроенные : []) {
    for (const id of (pb && pb.steps) || []) if (!out.includes(id)) out.push(id);
  }
  return out;
}

/** Настроен ли набор. Нужно, чтобы не предлагать «очистить» впустую. */
function настроен(хранилище) {
  return нормализовать(хранилище).хранилище.набор.steps.length > 0;
}

const API = {
  КЛЮЧ, ВЕРСИЯ, ID, ИМЯ_ПО_УМОЛЧАНИЮ,
  пусто, нормализовать, набор, список, типыПоСоставу,
  проверить, сохранить, очистить, поВстроенным, настроен,
};
глоб.TIMyPlaybooks = API;
if (typeof module !== 'undefined' && module.exports) module.exports = API;

})(typeof self !== 'undefined' ? self
   : (typeof globalThis !== 'undefined' ? globalThis : this));
