/**
 * Собрать все три формата.
 *
 * @param {Array}  items   индикаторы кейса
 * @param {object} опции   { название, tlp, режим, дата, свои, апи, sidОт }
 * @returns {{sigma, suricata, yara, заметки, подготовка}}
 */
function собрать(items, опции = {}) {
  const подг = подготовить(items, опции.свои, опции.апи || {}, опции);
  const заметки = [];

  if (!подг.всего) {
    return { sigma: '', suricata: '', yara: '', подготовка: подг,
             заметки: [T('в кейсе нет индикаторов, из которых можно собрать правило: ')
               + T('чистые и «не относится» в правила не идут намеренно')] };
  }

  const s = sigma(подг, опции);
  const su = suricata(подг, опции);
  const y = yara(подг, опции);

  if (подг.заменено.length) {
    заменённыеВЗаметки(подг, заметки);
  }
  if (подг.отброшено) {
    заметки.push(T`${подг.отброшено} значений не вошли: на тип берётся `
      + T`не больше ${опции.предел || ПРЕДЕЛ_ЗНАЧЕНИЙ}`);
  }
  for (const [тип, n] of подг.пропущеноТипов) {
    заметки.push(T`${тип}: ${n} значений — правило по такому типу не строится`);
  }
  for (const з of su.заметки) заметки.push(з);
  if (!s) заметки.push(T('Sigma: нечего положить в правило'));
  if (!su.текст) заметки.push(T('Suricata: нечего положить в правило'));
  if (!y) заметки.push(T('YARA: нечего положить в правило'));

  return { sigma: s, suricata: su.текст, yara: y, подготовка: подг, заметки };
}

function заменённыеВЗаметки(подг, заметки) {
  const домашние = подг.заменено.filter((з) => з.стало === '$HOME_NET').length;
  const клиентские = подг.заменено.filter((з) => з.стало === '$CLIENT_RANGES').length;
  const ч = [];
  if (домашние) ч.push(`${домашние} → $HOME_NET`);
  if (клиентские) ч.push(`${клиентские} → $CLIENT_RANGES`);
  заметки.push(T`Свои и клиентские адреса заменены плейсхолдерами (${ч.join(', ')}) `
    + T('и вынесены в исключение правила: правило на собственный адрес ловит ')
    + T('собственный трафик'));
}

function uuidv4() {
  if (typeof crypto !== 'undefined' && crypto.randomUUID) return crypto.randomUUID();
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}

/** Имя файла для сохранения. Название кейса в него не попадает никогда. */
function имяФайла(формат, дата) {
  const д = /^\d{4}-\d{2}-\d{2}$/.test(String(дата || ''))
    ? дата : new Date().toISOString().slice(0, 10);
  const рас = формат === 'sigma' ? 'yml' : формат === 'suricata' ? 'rules' : 'yar';
  return `ti-console-chernovik-${д}.${рас}`;
}

