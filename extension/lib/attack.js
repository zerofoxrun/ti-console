/* =============================================================================
 * attack.js — техники ATT&CK: проверка и расшифровка
 * =============================================================================
 *
 * ЧТО БЫЛО И ЧЕГО НЕ ХВАТАЛО
 * --------------------------
 * Каталог отвечал ровно на один вопрос — «существует ли такая техника».
 * Парсеру этого хватает: T9999 удовлетворяет формату, а техники нет,
 * и без каталога такая выдумка проходит в отчёт с отметкой
 * «подтверждено». Человеку не хватает: в отчёте T1059.001 — это
 * строка, значение которой он всё равно идёт смотреть в браузер,
 * а потом переписывает название в свой отчёт руками.
 *
 * Теперь каталог хранит идентификатор, название и тактики, а этот
 * модуль — единственное место, которое его читает.
 *
 * ПОЧЕМУ ЧИТАЕТ ОДИН МОДУЛЬ
 * -------------------------
 * До 0.43.0 каталог грузил модуль анализа моделью — своей функцией. Формат файла
 * изменился, и вторая такая функция, о которой забыли бы, не упала бы,
 * а МОЛЧА отдала пустой каталог: `new Set(объект)` бросает исключение,
 * оно ловится try/catch, и проверка техник тихо выключается. Ровно тот
 * отказ, который не видно ни в одном тесте интерфейса. Поэтому загрузка
 * здесь одна, а тот модуль спрашивает у неё.
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО
 * ------------------------
 * Описаний техник. Описание — это абзац текста на каждую из 918 техник,
 * то есть мегабайты в пакете; и читают его на сайте ATT&CK целиком,
 * а не по первой строке. Название и тактики отвечают на вопрос
 * «что это вообще», описание — на вопрос «как это работает»,
 * и за вторым надо идти к источнику.
 *
 * Ссылка тоже не хранится, а выводится: 918 раз один и тот же префикс
 * в файле — это килобайты ради нуля информации. Подтехника T1059.001
 * живёт по адресу .../techniques/T1059/001 — с косой чертой, не с точкой,
 * и это ровно та мелочь, из-за которой ссылка «почти работает».
 * ========================================================================== */

'use strict';

(function initAttack() {

if (typeof globalThis !== 'undefined' && globalThis.TIAttack) return;

const БАЗА = 'https://attack.mitre.org/techniques/';

let КАТАЛОГ = null;          // { tactics: [...], techniques: {...} }
let ЗАГРУЗКА = null;         // обещание, чтобы не грузить файл дважды

/** Где лежит файл каталога. Отличается в Node (тесты) и в браузере. */
function путь() {
  if (typeof browser !== 'undefined' && browser.runtime && browser.runtime.getURL) {
    return browser.runtime.getURL('data/attack-techniques.json');
  }
  return '../data/attack-techniques.json';
}

/**
 * Загрузить каталог. Повторные вызовы возвращают то же обещание.
 *
 * Ошибку НЕ глотаем в тишину: без каталога расшифровки не будет,
 * и вызывающий код обязан это различать. Поэтому при неудаче каталог
 * остаётся null, а загружен() отвечает false — а не «всё хорошо,
 * просто ничего не нашлось».
 */
function загрузить() {
  if (КАТАЛОГ) return Promise.resolve(КАТАЛОГ);
  if (ЗАГРУЗКА) return ЗАГРУЗКА;

  ЗАГРУЗКА = (async () => {
    let сырое;
    if (typeof module !== 'undefined' && module.exports && typeof require === 'function') {
      // Node: тесты и сверка с сервером. В браузере эта ветка недостижима.
      const fs = require('fs'), path = require('path');
      сырое = fs.readFileSync(
        path.join(__dirname, '..', 'data', 'attack-techniques.json'), 'utf8');
    } else {
      сырое = await (await fetch(путь())).text();
    }
    const d = JSON.parse(сырое);

    /* Форму проверяем явно. Файл генерируется, но именно поэтому:
     * сломавшийся генератор положит сюда что угодно, и «пустой каталог»
     * не должен выглядеть как «техника не найдена». */
    if (!d || typeof d.techniques !== 'object' || !Array.isArray(d.tactics)) {
      throw new Error(T('каталог ATT&CK не той формы'));
    }
    КАТАЛОГ = d;
    return КАТАЛОГ;
  })();

  ЗАГРУЗКА.catch(() => { ЗАГРУЗКА = null; });   // дать повторить попытку
  return ЗАГРУЗКА;
}

/** Загружен ли каталог. false — расшифровки не будет, и это надо сказать. */
function загружен() { return КАТАЛОГ !== null; }

/**
 * Чем каталог является: сколько записей, какой выпуск ATT&CK, когда собран.
 * null — каталога нет.
 *
 * ЗАЧЕМ ЭТО НУЖНО. Каталог лежит в пакете и читается молча — а значит,
 * на вопрос «есть ли он у меня и насколько он старый» ответить было
 * нечем. Устаревший на два выпуска каталог выглядит в точности как
 * свежий: техника из свежего отчёта не находится, и аналитик решает,
 * что в отчёте опечатка. Отличать «такой техники нет» от «мой каталог
 * её ещё не знает» должен интерфейс, а не догадка.
 *
 * Поля версии может не быть: каталоги, собранные до 0.45.0, её не несут.
 * Тогда честный ответ — null, а не выдуманный номер.
 */
function сводка() {
  if (!КАТАЛОГ) return null;
  const a = КАТАЛОГ.attack || {};
  return {
    записей: Object.keys(КАТАЛОГ.techniques).length,
    тактик: (КАТАЛОГ.tactics || []).length,
    версия: a['версия'] || null,
    собрано: a['собрано'] || null,
    матрицы: a['матрицы'] || null,
  };
}

/**
 * Техники указанной тактики.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ найти(). найти() отвечает на вопрос «что такое
 * T1059.001» — то есть требует уже знать идентификатор или название.
 * Вопрос «а что вообще относится к Execution» так не задать, а это
 * ровно тот вопрос, с которым к матрице и приходят, когда разбирают
 * поведение, а не готовый отчёт с проставленными кодами. Без него
 * каталог лежал в пакете, но спросить его было нечем.
 *
 * Сравнение по подстроке и без регистра: аналитик набирает «execution»,
 * а в каталоге «Execution»; «c2» при этом не должно находить
 * «Command and Control» — для этого есть поиск по названию техники.
 */
function поТактике(запрос, предел = 8) {
  if (!КАТАЛОГ) return [];
  const q = String(запрос || '').trim().toLowerCase();
  if (q.length < 3) return [];

  const подходят = new Set();
  КАТАЛОГ.tactics.forEach((t, i) => {
    if (String(t).toLowerCase().includes(q)) подходят.add(i);
  });
  if (!подходят.size) return [];

  const подошли = [];
  for (const id of Object.keys(КАТАЛОГ.techniques)) {
    const [, ts] = КАТАЛОГ.techniques[id];
    if ((ts || []).some((i) => подходят.has(i))) подошли.push(id);
  }

  /* Enterprise ВПЕРЁД, ICS — после.
   *
   * Идентификаторы ICS начинаются с T0, enterprise и mobile — с T1,
   * а ключи каталога отсортированы, то есть при простом обходе первыми
   * всегда шли T0800… И на запрос «lateral movement» аналитик SOC
   * получал восемь техник из матрицы для АСУ ТП, не увидев ни одной
   * из своей. Формально верно, практически бесполезно. */
  подошли.sort((a, b) => {
    /* Признак «не enterprise» берётся из каталога, а не из префикса:
     * шестнадцать техник ICS имеют обычный префикс T1 (T1691, T1692,
     * T1693 и подтехники), и сортировка по строке ставила бы их
     * вперемешку с enterprise. */
    const чужая = (x) => (матрица(x) === 'enterprise' || матрица(x) === null ? 0 : 1);
    return чужая(a) - чужая(b) || a.localeCompare(b);
  });
  return подошли.slice(0, предел).map((id) => техника(id));
}

/**
 * К какой матрице принадлежит техника: 'enterprise' | 'ics' | 'mobile'.
 * null — каталога нет, техники нет либо каталог собран до 0.47.0
 * и принадлежности в нём не записано.
 *
 * ПОЧЕМУ НЕ ПО ПРЕФИКСУ. Соблазн считать, что ICS — это всё, что
 * начинается на T0, и он почти верен: 81 техника ICS из 97 именно
 * такие. Но шестнадцать — нет: T1691, T1692, T1693 и их подтехники
 * живут в матрице ICS с обычным префиксом T1. Отбор по префиксу
 * пропускал их в enterprise молча, и поймал это только тест.
 */
function матрица(id) {
  if (!КАТАЛОГ) return null;
  const з = КАТАЛОГ.techniques[нормализовать(id)];
  const биты = з && з[2];
  if (!биты) return null;
  if (биты & 1) return 'enterprise';
  if (биты & 2) return 'ics';
  if (биты & 4) return 'mobile';
  return null;
}

/** Платформы техники словами. Пустой массив — каталог без платформ. */
function площадки(id) {
  if (!КАТАЛОГ || !Array.isArray(КАТАЛОГ.platforms)) return [];
  const з = КАТАЛОГ.techniques[нормализовать(id)];
  return ((з && з[3]) || []).map((i) => КАТАЛОГ.platforms[i]).filter(Boolean);
}

/** Весь каталог как есть — для модели матрицы. null, если не загружен. */
function каталог() { return КАТАЛОГ; }

/** Существует ли техника. null — каталога нет, ответить нечем. */
function существует(id) {
  if (!КАТАЛОГ) return null;
  return Object.prototype.hasOwnProperty.call(КАТАЛОГ.techniques, нормализовать(id));
}

/**
 * Расшифровка техники.
 *   null — каталога нет ИЛИ техники в нём нет. Различать эти два случая
 *   должен вызывающий: загружен() отвечает на первый вопрос.
 */
function техника(id) {
  if (!КАТАЛОГ) return null;
  const ключ = нормализовать(id);
  const зап = КАТАЛОГ.techniques[ключ];
  if (!зап) return null;
  const [название, тактики] = зап;
  return {
    id: ключ,
    название,
    тактики: (тактики || []).map((i) => КАТАЛОГ.tactics[i]).filter(Boolean),
    url: ссылка(ключ),
  };
}

/** Ссылка на страницу техники. Подтехника — через косую черту. */
function ссылка(id) {
  return БАЗА + нормализовать(id).replace('.', '/');
}

/** Родительская техника подтехники: T1059.001 -> T1059. null для базовой. */
function родитель(id) {
  const к = нормализовать(id);
  const i = к.indexOf('.');
  return i === -1 ? null : к.slice(0, i);
}

/* Каноническая форма уже делается в ioc.js (T1574/001/ -> T1574.001),
 * но сюда значение может прийти и не оттуда — из плейбука, из кода,
 * из вставленного вручную поля. Повтор нормализации дешевле, чем
 * разбирательство «почему из парсера работает, а из поля нет». */
function нормализовать(id) {
  return String(id || '').trim().toUpperCase().replace(/\//g, '.').replace(/\.$/, '');
}

/**
 * Строка для отчёта: «T1059.001 — PowerShell (Execution)».
 * Без каталога — сам идентификатор: строка обязана остаться читаемой,
 * а не превратиться в «undefined».
 */
function строка(id) {
  const т = техника(id);
  if (!т) return нормализовать(id);
  const тактики = т.тактики.length ? ` (${т.тактики.join(', ')})` : '';
  return `${т.id} — ${т.название}${тактики}`;
}

/**
 * Поиск техник по идентификатору или по названию.
 *
 * Два способа искать, потому что аналитик приходит с двух сторон:
 * из отчёта — с идентификатором («T1059.001»), из разговора —
 * с названием («powershell»). Точное совпадение идентификатора идёт
 * первым: набрав T1059, человек хочет именно её, а не двадцать техник,
 * в названии которых встретилось «1059».
 */
function найти(запрос, предел = 8) {
  if (!КАТАЛОГ) return [];
  const q = String(запрос || '').trim().toLowerCase();
  if (q.length < 2) return [];

  const поId = [], поНазванию = [];
  const норм = нормализовать(q);
  for (const id of Object.keys(КАТАЛОГ.techniques)) {
    if (id === норм) { поId.unshift(id); continue; }
    if (id.toLowerCase().startsWith(q)) { поId.push(id); continue; }
    if (КАТАЛОГ.techniques[id][0].toLowerCase().includes(q)) поНазванию.push(id);
    if (поId.length + поНазванию.length > предел * 4) break;   // хватит
  }
  /* Enterprise вперёд, потом короткие названия.
   *
   * Порядок ключей каталога — алфавитный, а идентификаторы ICS
   * начинаются с T0, то есть при равных правах они всегда оказывались
   * первыми: на «download» аналитик SOC получал «T0843 — Program
   * Download» из матрицы для АСУ ТП прежде своих. Та же поправка, что
   * в поТактике(), и по той же причине. ICS не выбрасываются —
   * у части заказчиков АСУ ТП есть.
   *
   * Короткие названия вперёд внутри своей группы: «PowerShell» полезнее,
   * чем «PowerShell Profile Modification», когда набрано «powershell». */
  const ics = (x) => (x.startsWith('T0') ? 1 : 0);
  поНазванию.sort((a, b) =>
    ics(a) - ics(b)
    || КАТАЛОГ.techniques[a][0].length - КАТАЛОГ.techniques[b][0].length);

  return поId.concat(поНазванию).slice(0, предел).map(техника).filter(Boolean);
}

/** Только для тестов: подставить каталог, в том числе пустой. */
function __setCatalog(d) {
  КАТАЛОГ = d;
  ЗАГРУЗКА = d ? Promise.resolve(d) : null;
}

const ATTACK_API = {
  загрузить, загружен, сводка, существует, техника, ссылка, родитель, строка, найти,
  матрица, площадки, каталог,
  поТактике,
  нормализовать, __setCatalog,
};
if (typeof module !== 'undefined' && module.exports) module.exports = ATTACK_API;
if (typeof globalThis !== 'undefined') globalThis.TIAttack = ATTACK_API;

})();
