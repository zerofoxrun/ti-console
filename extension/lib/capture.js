/* =============================================================================
 * capture.js — сбор индикаторов с помеченной вкладки
 * =============================================================================
 *
 * ЧТО ЭТО
 * -------
 * Аналитик нажимает «Собирать с этой вкладки». Дальше каждая страница,
 * открытая В ЭТОЙ вкладке, разбирается сама, и найденное копится
 * в очереди триажа. Остальные вкладки — почта, SIEM, порталы клиентов —
 * не трогаются вовсе.
 *
 * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ SESSION CAPTURE У APERTURE
 * ------------------------------------------------
 * У них сбор идёт со всех открываемых страниц, потому что постоянный
 * content-script и так стоит везде. Цена — обязательное разрешение
 * на все сайты и невозможность объяснить заказчику, что именно
 * расширение читало на его портале.
 *
 * Здесь граница проходит по ВКЛАДКЕ, и это не смягчение той же идеи,
 * а другая: аналитик открывает отчёт в отдельной вкладке и помечает
 * её. Всё, что он делает в остальных вкладках, к сбору отношения
 * не имеет.
 *
 * ПОЧЕМУ В ОЧЕРЕДЬ, А НЕ В КЕЙС
 * -----------------------------
 * Кейс — утверждение о расследовании: что в нём лежит, то уедет
 * в отчёт и в выгрузку. Автоматически ссыпать туда всё найденное
 * значит сделать кейс свалкой из баннеров, cdn и счётчиков
 * с попутных страниц. Очередь триажа ровно для этого промежутка
 * и делалась: «нашлось» отдельно, «решено» отдельно.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ, А ЧЕГО НЕТ
 * --------------------------
 * Здесь — чистое состояние сбора и правила его окончания. Ни DOM,
 * ни хранилища, ни разрешений: всё это в фоне, а сюда сводятся
 * решения, которые обязаны проверяться без браузера.
 *
 * ПРЕДЕЛЫ — ОБЯЗАТЕЛЬНАЯ ЧАСТЬ, А НЕ ПЕРЕСТРАХОВКА
 * ------------------------------------------------
 * Забытый включённым сбор — это расширение, которое молча читает
 * страницы час за часом. Поэтому сеанс кончается сам: по числу
 * страниц, по времени и вместе с вкладкой. Каждое окончание
 * НАЗЫВАЕТСЯ: «сбор остановлен — 200 страниц» лучше, чем тишина,
 * в которой аналитик думает, что сбор идёт.
 * ========================================================================== */
(function () {
'use strict';

const КЛЮЧ = 'ti_capture';
const ПРЕДЕЛ_СТРАНИЦ = 200;
const ПРЕДЕЛ_МС = 2 * 60 * 60 * 1000;      // два часа
const МИН_ПАУЗА_МС = 800;                   // защита от каскада перерисовок

const ПРИЧИНЫ = {
  человек: T('остановлен аналитиком'),
  вкладка: T('вкладка закрыта'),
  страницы: T`набрано ${ПРЕДЕЛ_СТРАНИЦ} страниц — предел сеанса`,
  время: T('прошло два часа — предел сеанса'),
  чужойСайт: T('вкладка ушла на другой сайт, на который нет разрешения'),
};

function пусто() {
  return null;
}

/**
 * Начать сбор.
 * @param {number} tabId
 * @param {string} url      адрес, с которого начали
 * @param {number} сейчас
 */
function начать(tabId, url, сейчас = Date.now()) {
  return {
    tabId: Number(tabId),
    источник: источникИз(url),
    начат: сейчас,
    последний: 0,
    страниц: 0,
    найдено: 0,
    добавлено: 0,
    адреса: [],
  };
}

function источникИз(url) {
  try { return new URL(String(url)).origin; } catch (_) { return ''; }
}

/**
 * Можно ли разбирать эту страницу в рамках сеанса.
 *
 * Возвращает {годится, причина, стоп}. `стоп` означает, что сеанс
 * надо прекратить, а не просто пропустить страницу: уход на другой
 * сайт — это не «пропустим одну», а конец разрешения.
 */
function проверитьСтраницу(сеанс, tabId, url, сейчас = Date.now()) {
  if (!сеанс) return { годится: false, причина: T('сбор не идёт') };
  if (Number(tabId) !== сеанс.tabId) return { годится: false, причина: T('другая вкладка') };

  if (сеанс.страниц >= ПРЕДЕЛ_СТРАНИЦ) {
    return { годится: false, стоп: true, причина: ПРИЧИНЫ.страницы };
  }
  if (сейчас - сеанс.начат >= ПРЕДЕЛ_МС) {
    return { годится: false, стоп: true, причина: ПРИЧИНЫ.время };
  }

  const u = String(url || '');
  if (/^(about|chrome|moz-extension|resource|view-source|file):/i.test(u)) {
    return { годится: false, причина: T('служебная страница') };
  }
  if (!/^https?:\/\//i.test(u)) return { годится: false, причина: 'не http(s)' };

  /* Уход на другой сайт прекращает сеанс. Разрешение аналитик давал
   * на конкретный сайт, и молча продолжить на соседнем — это взять
   * больше, чем дали. */
  if (сеанс.источник && источникИз(u) !== сеанс.источник) {
    return { годится: false, стоп: true, причина: ПРИЧИНЫ.чужойСайт };
  }

  /* Одна и та же страница, перерисованная скриптами, не должна
   * разбираться десять раз подряд. */
  if (сеанс.последний && сейчас - сеанс.последний < МИН_ПАУЗА_МС) {
    return { годится: false, причина: T('слишком часто') };
  }
  return { годится: true, причина: '' };
}

/** Записать разобранную страницу в сеанс. */
function учесть(сеанс, url, найдено, добавлено, сейчас = Date.now()) {
  if (!сеанс) return сеанс;
  const адреса = сеанс.адреса.concat([{ url: String(url || ''), при: сейчас,
                                        найдено: Number(найдено) || 0 }]);
  return {
    ...сеанс,
    последний: сейчас,
    страниц: сеанс.страниц + 1,
    найдено: сеанс.найдено + (Number(найдено) || 0),
    добавлено: сеанс.добавлено + (Number(добавлено) || 0),
    /* История адресов нужна для строки «собрано с 12 страниц», но
     * расти без предела она не должна: это профиль браузера, а не
     * журнал. Держим последние 30. */
    адреса: адреса.slice(-30),
  };
}

/** Строка для человека: что происходит прямо сейчас. */
function подпись(сеанс) {
  if (!сеанс) return T('сбор не идёт');
  return T`собираю с этой вкладки · страниц ${сеанс.страниц} · `
       + T`в очередь ${сеанс.добавлено}`;
}

/** Строка по окончании. Причина называется всегда. */
function итог(сеанс, причина) {
  if (!сеанс) return T('сбор не шёл');
  return T`Сбор остановлен (${причина || ПРИЧИНЫ.человек}): страниц ${сеанс.страниц}, `
       + T`найдено ${сеанс.найдено}, в очередь добавлено ${сеанс.добавлено}.`;
}

/** Пережил ли сеанс перезапуск браузера. Идентификаторы вкладок после
 *  перезапуска чужие, и продолжать сбор в «той же» вкладке нельзя. */
function живой(сеанс, живыеВкладки) {
  if (!сеанс) return false;
  const список = Array.isArray(живыеВкладки) ? живыеВкладки.map(Number) : [];
  return список.includes(Number(сеанс.tabId));
}

const API = {
  КЛЮЧ, ПРЕДЕЛ_СТРАНИЦ, ПРЕДЕЛ_МС, МИН_ПАУЗА_МС, ПРИЧИНЫ,
  пусто, начать, проверитьСтраницу, учесть, подпись, итог, живой, источникИз,
};
if (typeof module !== 'undefined' && module.exports) module.exports = API;
if (typeof globalThis !== 'undefined') globalThis.TICapture = API;

})();
