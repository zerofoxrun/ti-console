// ЛОКАЛИЗАЦИЯ ИНТЕРФЕЙСА
// ----------------------
// Исходный язык разметки и кода — русский. Он же служит КЛЮЧОМ словаря:
// T('Открыть кейс') при языке en вернёт 'Open case', при ru — исходную
// строку. Отдельных символьных ключей нет намеренно:
//
//   1. ключи не нужно придумывать и поддерживать в двух местах;
//   2. строка без перевода деградирует в читаемый русский текст,
//      а не в 'newtab.case.open', который пользователю ничего не скажет;
//   3. при языке ru словарь вообще не участвует — T() возвращает аргумент,
//      то есть поведение продукта до локализации и после побитово совпадает.
//      Этим пользуются тесты: они продолжают проверять русские строки.
//
// ЯЗЫК ПО УМОЛЧАНИЮ — АНГЛИЙСКИЙ. Это решение для магазина: карточка,
// снимки экрана и первый запуск у незнакомого пользователя должны быть
// на английском. Русский включается переключателем в шапке и запоминается
// в storage.local, ключ ti_lang.
//
// ПЕРЕКЛЮЧЕНИЕ ПЕРЕЗАГРУЖАЕТ СТРАНИЦУ. Альтернатива — перерисовать всё
// живое состояние на новом языке — требует, чтобы каждый компонент умел
// перерисоваться без потери данных. Перезагрузка стоит 200 мс и не может
// разойтись с состоянием; кейс и настройки лежат в storage и переживают её.

(function (глоб) {
  'use strict';

  var КЛЮЧ_ЯЗЫКА = 'ti_lang';
  var ЯЗЫКИ = ['en', 'ru'];
  var ПО_УМОЛЧАНИЮ = 'en';

  var язык = ПО_УМОЛЧАНИЮ;
  var словарь = {};
  var готово = false;

  // Атрибуты, которые видит пользователь. value и alt сознательно не трогаем:
  // value у select и input — это данные, а не подпись.
  var АТРИБУТЫ = ['title', 'placeholder', 'aria-label'];

  // Узлы, внутрь которых переводчик не заходит: там не подписи, а код,
  // данные пользователя или уже переведённое содержимое.
  // CODE намеренно НЕ пропускаем: в разметке им размечены однословные
  // подписи («ЧЕРНОВИК»), и пропуск оставлял их русскими. Риск задеть
  // пример кода мал — в словаре только строки интерфейса. PRE остаётся
  // в списке: там лежат многострочные примеры целиком.
  var ПРОПУСК = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, PRE: 1 };

  // Ключ текстового узла: обрезали края и схлопнули внутренние пробелы.
  // Без схлопывания узел, разорванный переносом строки в исходнике,
  // не совпал бы ни с одним ключом словаря — и остался бы русским,
  // причём молча. Именно так теряется половина длинных подписей.
  function ключТекста(с) {
    return с.replace(/\s+/g, ' ').trim();
  }

  function хранилище() {
    if (typeof browser !== 'undefined' && browser.storage) return browser.storage.local;
    if (typeof chrome !== 'undefined' && chrome.storage) return chrome.storage.local;
    return null;
  }

  function нормализовать(знач) {
    return ЯЗЫКИ.indexOf(знач) >= 0 ? знач : ПО_УМОЛЧАНИЮ;
  }

  // Словари лежат в глобальных переменных: locales/en.js объявляет
  // TI_LOCALE_EN. Русского словаря нет и не будет — он тождественный.
  function словарьДля(яз) {
    if (яз === 'en' && глоб.TI_LOCALE_EN) return глоб.TI_LOCALE_EN;
    return {};
  }

  // Ключ шаблонной строки: куски literal'а, склеенные через {0}, {1}, …
  // `Найдено ${n} из ${m}` -> 'Найдено {0} из {1}'. Такой ключ читается
  // в словаре глазами и переживает перестановку подстановок в переводе.
  function ключШаблона(части, сколько) {
    var s = '';
    for (var i = 0; i < части.length; i++) {
      s += части[i];
      if (i < сколько) s += '{' + i + '}';
    }
    return s;
  }

  function подставить(строка, арги) {
    if (!арги.length) return строка;
    return строка.replace(/\{(\d+)\}/g, function (всё, н) {
      var v = арги[+н];
      return v === undefined ? всё : String(v);
    });
  }

  // T работает и как обычная функция, и как тег шаблонной строки:
  //   T('Открыть кейс')
  //   T('Найдено {0}', n)
  //   T`Найдено ${n} индикаторов`
  function T(первый) {
    var арги = Array.prototype.slice.call(arguments, 1);
    var ключ;
    if (первый && первый.raw && Array.isArray(первый)) {
      /* Берём «варёные» куски (сам массив), а не .raw: в обычной строке
       * '…,\n' движок JS уже превратил \n в перевод строки, и ключ из
       * .raw расходился бы с ключом такой же строки в кавычках.
       * Из-за этого подпись версии молча оставалась русской. */
      ключ = ключШаблона(первый, арги.length);
    } else {
      ключ = String(первый);
    }
    var перевод = Object.prototype.hasOwnProperty.call(словарь, ключ) ? словарь[ключ] : ключ;
    return подставить(перевод, арги);
  }

  // Перевод статической разметки. Запускается один раз, до того как
  // страница начнёт рисовать динамику: всё, что появляется позже,
  // проходит через T() в коде. Повторный проход по уже переведённому
  // тексту безвреден — в словаре нет английских ключей.
  function применитьКDOM(корень) {
    if (язык === 'ru') return 0;
    var узел = корень || document.body;
    if (!узел) return 0;
    var сколько = 0;

    var обход = document.createTreeWalker(узел, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        if (n.parentNode && ПРОПУСК[n.parentNode.nodeName]) return NodeFilter.FILTER_REJECT;
        return n.nodeValue && /[А-Яа-яЁё]/.test(n.nodeValue)
          ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      },
    });
    var текстовые = [];
    for (var n = обход.nextNode(); n; n = обход.nextNode()) текстовые.push(n);
    текстовые.forEach(function (n) {
      var исходный = n.nodeValue;
      var ключ = ключТекста(исходный);
      if (!ключ) return;
      if (!Object.prototype.hasOwnProperty.call(словарь, ключ)) return;
      // Ведущий и замыкающий пробелы сохраняем: от них зависят отступы
      // в строках вида «Кейс: <strong>0</strong>». Внутренние переносы
      // исходника не сохраняем — они были форматированием файла.
      var слева = /^\s/.test(исходный) ? ' ' : '';
      var справа = /\s$/.test(исходный) ? ' ' : '';
      n.nodeValue = слева + словарь[ключ] + справа;
      сколько++;
    });

    var все = узел.querySelectorAll('*');
    for (var i = 0; i < все.length; i++) {
      for (var a = 0; a < АТРИБУТЫ.length; a++) {
        var имя = АТРИБУТЫ[a];
        var знач = все[i].getAttribute(имя);
        if (!знач || !/[А-Яа-яЁё]/.test(знач)) continue;
        var кл = ключТекста(знач);
        if (!Object.prototype.hasOwnProperty.call(словарь, кл)) continue;
        все[i].setAttribute(имя, словарь[кл]);
        сколько++;
      }
    }
    return сколько;
  }

  // Инициализация: читаем язык, подключаем словарь, переводим разметку.
  // Возвращает выбранный язык. Вызывать до первой отрисовки.
  function инициализация(опции) {
    var о = опции || {};
    var хр = хранилище();
    return new Promise(function (ок) {
      if (!хр) { ок(ПО_УМОЛЧАНИЮ); return; }
      try {
        var р = хр.get(КЛЮЧ_ЯЗЫКА);
        if (р && typeof р.then === 'function') {
          р.then(function (д) { ок(нормализовать(д && д[КЛЮЧ_ЯЗЫКА])); },
                 function () { ок(ПО_УМОЛЧАНИЮ); });
        } else {
          хр.get(КЛЮЧ_ЯЗЫКА, function (д) { ок(нормализовать(д && д[КЛЮЧ_ЯЗЫКА])); });
        }
      } catch (e) { ок(ПО_УМОЛЧАНИЮ); }
    }).then(function (яз) {
      // storage.local — источник истины: его видит политика и он
      // переживает очистку сайтовых данных. localStorage — лишь копия
      // для синхронного старта; если копия отстала, чиним её здесь.
      if (страницаРасширения()) {
        try { localStorage.setItem(КЛЮЧ_ЯЗЫКА, яз); } catch (e) { /* не критично */ }
      }
      язык = яз;
      словарь = словарьДля(яз);
      готово = true;
      if (typeof document !== 'undefined' && document.documentElement) {
        document.documentElement.setAttribute('lang', яз);
      }
      if (о.dom !== false && typeof document !== 'undefined') применитьКDOM(о.корень);
      return яз;
    });
  }

  function сохранить(яз) {
    var хр = хранилище();
    яз = нормализовать(яз);
    // Сначала синхронная копия: перезагрузка после смены языка
    // происходит раньше, чем успевает ответить storage.local.
    if (страницаРасширения()) {
      try { localStorage.setItem(КЛЮЧ_ЯЗЫКА, яз); } catch (e) { /* не критично */ }
    }
    if (!хр) return Promise.resolve(яз);
    var объект = {}; объект[КЛЮЧ_ЯЗЫКА] = яз;
    return new Promise(function (ок) {
      try {
        var р = хр.set(объект);
        if (р && typeof р.then === 'function') р.then(function () { ок(яз); }, function () { ок(яз); });
        else ок(яз);
      } catch (e) { ок(яз); }
    });
  }

  // СИНХРОННЫЙ СТАРТ.
  // storage.local асинхронен, а T() вызывается уже при загрузке скрипта:
  // таблицы подписей и начальное состояние объявлены на верхнем уровне
  // модулей. К моменту, когда инициализация() дождётся хранилища, эти
  // строки давно вычислены — и остались бы русскими навсегда.
  // Поэтому язык дублируется в localStorage, который читается
  // синхронно, и словарь подключается прямо здесь.
  //
  // Только на страницах расширения: в content-script localStorage
  // принадлежит ЧУЖОМУ сайту, писать туда нельзя, а читать бессмысленно.
  function страницаРасширения() {
    try {
      return typeof location !== 'undefined'
        && /^(moz|chrome)-extension:$/.test(location.protocol);
    } catch (e) { return false; }
  }

  (function синхронныйСтарт() {
    if (!страницаРасширения()) return;
    try {
      var з = localStorage.getItem(КЛЮЧ_ЯЗЫКА);
      язык = нормализовать(з);
      словарь = словарьДля(язык);
    } catch (e) { /* приватный режим: останется язык по умолчанию */ }
  })();

  var API = {
    T: T,
    t: T,
    инициализация: инициализация,
    применитьКDOM: применитьКDOM,
    сохранить: сохранить,
    языки: function () { return ЯЗЫКИ.slice(); },
    язык: function () { return язык; },
    готово: function () { return готово; },
    поУмолчанию: ПО_УМОЛЧАНИЮ,
    ключХранилища: КЛЮЧ_ЯЗЫКА,
    // для тестов: подменить словарь и язык без обращения к хранилищу
    _установить: function (яз, слов) {
      язык = нормализовать(яз);
      словарь = слов || словарьДля(язык);
      готово = true;
      return язык;
    },
  };

  глоб.TII18n = API;
  глоб.T = T;

  if (typeof module !== 'undefined' && module.exports) module.exports = API;
})(typeof self !== 'undefined' ? self
   : (typeof globalThis !== 'undefined' ? globalThis : this));
